/* Товарный чек: одна кнопка — «Распечатать».
 *
 * Свой файл, а не строчка в app.js: тот везёт корзину, галерею и метрику, и
 * ради одной кнопки тащить его на страницу документа незачем. Inline-обработчик
 * тоже не годится — у витрины `script-src 'self'`, и `onclick` в разметке
 * браузер просто не выполнит.
 *
 * PDF мы не генерируем и генерировать нечем: внешних зависимостей у проекта
 * нет. Сохранение в PDF делает сам браузер из окна печати — там эта кнопка и
 * стоит первой строкой в списке «принтеров».
 */
(function () {
  'use strict';
  var btn = document.querySelector('[data-print]');
  if (!btn) return;
  btn.addEventListener('click', function () { window.print(); });
})();
