'use strict';
/*
 * На телефоне сайт обязан вести себя как приложение, а не как страница.
 *
 * Что было: страницу можно было увеличить щипком, а увеличенную — таскать
 * вправо-влево. После этого экран оставался съехавшим, и хуже всего это
 * выглядело в чате: у `position:fixed` координаты считаются от layout viewport,
 * поэтому окно чата стояло шире видимой области и по краям торчала витрина.
 * Со стороны это читается не как «я увеличил страницу», а как поехавшая вёрстка.
 *
 * Половину делает мета-тег (`maximum-scale=1, user-scalable=no` в `layout()`
 * обоих макетов), но Safari щипок пользователю оставляет намеренно — этими
 * атрибутами он не управляется. Вторая половина здесь.
 *
 * Файл ОДИН на витрину и панель: правило «ведёт себя как приложение» общее, а
 * две копии разъехались бы на первой правке. Он же самый маленький скрипт в
 * проекте — грузится первым и ничего не ждёт.
 */
(function () {
  /* Щипок. `gesturestart`/`gesturechange`/`gestureend` — собственные события
     Safari, и это единственная ручка, которой масштаб страницы там гасится.
     `passive:false` обязателен: без него `preventDefault()` браузер
     проигнорирует. В остальных браузерах этих событий просто нет. */
  ['gesturestart', 'gesturechange', 'gestureend'].forEach(function (name) {
    document.addEventListener(name, function (e) { e.preventDefault(); }, { passive: false });
  });

  /* Двойной тап здесь НЕ перехватывается, и это осознанно: подавить его можно
     только `preventDefault()` на `touchend`, а он заодно съедает второй click —
     быстрые повторные нажатия по «+» в счётчике количества или по стрелке
     галереи переставали срабатывать. Двойной тап гасит CSS
     (`touch-action:manipulation` у body), и делает это, ничего не ломая. */

  /* Горизонтальный сдвиг окна. У body стоит `overflow-x:hidden`, поэтому в
     обычной жизни сдвигу взяться неоткуда, — но клавиатура на iOS двигает
     страницу сама, и это ровно тот случай, когда экран остаётся съехавшим, а
     вернуть его пальцем нельзя. Возвращаем вертикальную позицию как есть:
     трогаем только горизонталь. */
  function unshift() {
    if (window.scrollX !== 0) window.scrollTo(0, window.scrollY);
  }
  window.addEventListener('scroll', unshift, { passive: true });
  window.addEventListener('orientationchange', unshift);

  /* Клавиатура выезжает уже ПОСЛЕ того, как фокус встал в поле, и сдвиг
     появляется вместе с ней — то же запаздывание в пару кадров, из-за которого
     окно чата подгоняется по фокусу (`fitViewport` в public/chat.js). */
  document.addEventListener('focusin', function () { setTimeout(unshift, 200); });

  var vv = window.visualViewport;
  if (vv) {
    vv.addEventListener('resize', function () { setTimeout(unshift, 0); });
    vv.addEventListener('scroll', unshift);
  }

  /* ---------- Панель во весь экран садится в ВИДИМУЮ область ----------
   *
   * Открывая клавиатуру, Safari и Chrome НЕ уменьшают окно, а сдвигают видимую
   * область вверх. Элемент с `position:fixed;inset:0` остаётся при этом на
   * месте по документу: его шапка уезжает за верхний край, а поле ввода — под
   * клавиатуру. Медиазапросами этого не сделать — они про размер ОКНА, а не про
   * видимую его часть; `100dvh` знает про адресную строку, но не про клавиатуру.
   *
   * Функция ОДНА на витрину и панель: окно чата у покупателя и страница диалога
   * у менеджера решают одну задачу, и копия этой арифметики во втором файле
   * разъехалась бы с первой — а увидеть это можно только на живом телефоне.
   * Живёт она здесь, потому что этот файл грузят оба макета и грузят первым.
   *
   * Возвращает true, если панель пришлось подвинуть: вызывающий по этому знаку
   * доводит ленту до последней реплики.
   */
  function reset(el) {
    if (!el.style.height && !el.style.width && !el.style.transform) return false;
    el.style.removeProperty('width');
    el.style.removeProperty('height');
    el.style.removeProperty('transform');
    return false;
  }
  window.fitPanel = function (el, on) {
    if (!el) return false;
    if (!vv || !on) return reset(el);
    var keyboard = window.innerHeight - vv.height > 80;
    /* Видимая область бывает сдвинута и без клавиатуры — щипком. Масштаб мы
       гасим выше, но щипок мог случиться до загрузки скрипта или в браузере,
       который событий не отдаёт. Проверяем, а не верим. */
    var shifted = Math.abs(vv.offsetLeft) > 1 || Math.abs(vv.offsetTop) > 1;
    var zoomed = Math.abs((vv.scale || 1) - 1) > 0.01;
    // Всё на своих местах — не трогаем ничего: лишний inline-стиль перебил бы
    // анимацию открытия и обычную раскладку.
    if (!keyboard && !shifted && !zoomed) return reset(el);
    el.style.width = vv.width + 'px';
    el.style.height = vv.height + 'px';
    // Сдвиг именно transform, а не top/left: он идёт в композиторе и не
    // заставляет пересчитывать раскладку на каждый кадр выезжающей клавиатуры.
    el.style.transform = 'translate(' + vv.offsetLeft + 'px,' + vv.offsetTop + 'px)';
    return true;
  };
})();
