'use strict';
/* ========================= Звуки чата: пришло и ушло =========================
 *
 * Два коротких сигнала, знакомых по любому мессенджеру: мягкая двойная нота на
 * входящее сообщение и лёгкий щелчок на отправленное. Отвечают они на вопрос,
 * ради которого звук в чате и нужен: «мне ответили», когда окно закрыто или
 * вкладка не та.
 *
 * ФАЙЛОВ СО ЗВУКАМИ ЗДЕСЬ НЕТ, И ЭТО НЕ ЛЕНЬ. Взять готовые сигналы WhatsApp
 * или Telegram нельзя: это чужие произведения с их правами, а лежать они будут
 * в открытом репозитории магазина. Да и по устройству проекта они не подходят —
 * пара mp3 это лишние запросы на каждого посетителя и первые бинарники в дереве
 * без единой зависимости. Поэтому сигнал СИНТЕЗИРУЕТСЯ на месте: три осциллятора
 * на всё про всё, ноль байт трафика, и звучит он ровно так же на любом
 * устройстве, где вообще есть звук.
 *
 * ХАРАКТЕР ВЗЯТ ОТТУДА ЖЕ, ОТКУДА ЕГО БЕРУТ ВСЕ. Входящее — восходящая чистая
 * квинта (ля → ми) с быстрым затуханием: две ноты читаются как «событие», одна
 * звучит как сигнал ошибки. Исходящее — одиночная нота выше и заметно тише: она
 * подтверждает своё же действие, и громкость ей ни к чему.
 *
 * ОДИН ФАЙЛ НА ВИТРИНУ И ПАНЕЛЬ — то же правило, что у `public/phone.js` и
 * `public/media-lightbox.js`: правило «как звучит чат» общее, а две копии
 * разошлись бы на первой правке, и покупатель с менеджером слышали бы разное.
 */
(function () {
  // Синус мягче всего: пилообразные и прямоугольные волны на таких частотах
  // режут слух в наушниках, а сигнал обязан быть приятным — его слышат десятки
  // раз за день.
  var TONE = 'sine';
  /* Ноты и их место в сигнале: [частота, задержка от начала, длительность].
   * Частоты — равномерный строй: A5 880, E6 1318.51, G6 1567.98. */
  var SOUNDS = {
    in: { gain: 0.10, notes: [[880, 0, 0.28], [1318.51, 0.085, 0.34]] },
    out: { gain: 0.05, notes: [[1567.98, 0, 0.16]] }
  };
  // Выше этого сигнал становится «пищащим» — срезаем верх мягким фильтром.
  var CUTOFF = 3600;
  var ATTACK = 0.006;   // мгновенная атака щёлкает; шесть миллисекунд её убирают

  var ctx = null;
  var broken = false;

  /* Звук в браузере нельзя завести до первого действия человека: автоплей
   * запрещён везде. Поэтому контекст создаётся ЛЕНИВО, при первой же попытке
   * сыграть, и пробуждается на любом жесте. Не получилось — молчим: чат обязан
   * работать и без звука, и ронять его из-за политики автоплея нельзя. */
  function audio() {
    if (broken) return null;
    if (ctx) return ctx;
    var Ctor = window.AudioContext || window.webkitAudioContext;
    if (!Ctor) { broken = true; return null; }
    try { ctx = new Ctor(); } catch (e) { broken = true; return null; }
    return ctx;
  }

  // Первый жест страницы будит контекст заранее, чтобы самый первый сигнал не
  // пропал: у покупателя это нажатие кнопки чата, у менеджера — любой клик.
  function arm() {
    var c = audio();
    if (c && c.state === 'suspended') c.resume().catch(function () {});
  }
  document.addEventListener('pointerdown', arm, { once: true, passive: true });
  document.addEventListener('keydown', arm, { once: true });

  function play(name) {
    var spec = SOUNDS[name];
    var c = spec && audio();
    if (!c) return;
    // Вкладка спит — планировщик всё равно не отдаст звук вовремя, а
    // разбуженный контекст сыграет накопленное пачкой при возврате.
    if (c.state === 'suspended') { c.resume().catch(function () {}); }
    try {
      var now = c.currentTime;
      var master = c.createGain();
      master.gain.value = spec.gain;
      var soft = c.createBiquadFilter();
      soft.type = 'lowpass';
      soft.frequency.value = CUTOFF;
      master.connect(soft);
      soft.connect(c.destination);
      for (var i = 0; i < spec.notes.length; i++) {
        var note = spec.notes[i];
        var at = now + note[1];
        var osc = c.createOscillator();
        osc.type = TONE;
        osc.frequency.value = note[0];
        var env = c.createGain();
        // Затухание экспонентой, а не линией: линейное гаснет «ступенькой» и
        // слышится как обрыв. К нулю exponentialRamp не идёт вовсе — отсюда
        // мизерное конечное значение и обрубание тишины в конце.
        env.gain.setValueAtTime(0.0001, at);
        env.gain.exponentialRampToValueAtTime(1, at + ATTACK);
        env.gain.exponentialRampToValueAtTime(0.0001, at + note[2]);
        osc.connect(env);
        env.connect(master);
        osc.start(at);
        osc.stop(at + note[2] + 0.02);
      }
    } catch (e) { /* звук — не то, ради чего стоит ронять чат */ }
  }

  window.ChatSound = { play: play };
})();
