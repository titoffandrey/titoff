'use strict';
// Способы доставки. Список закрытый и один на всех: по нему рисуется выбор на
// оформлении, проверяется заказ на сервере и подписывается строка в панелях.
// Отдельный модуль, а не константа в render.js, потому что список нужен и в
// lib/db.js при нормализации заказа — а db.js рендер не подключает и не должен
// (render -> tenancy -> db, вышел бы цикл).
//
// id пишется в заказ и остаётся в старых заявках навсегда, поэтому менять их
// нельзя — только добавлять новые. Название можно править свободно.
//
// У каждого способа два варианта доставки (`modes`): в пункт выдачи и курьером
// до двери. Это не украшение выбора, а две разные цены: у обоих перевозчиков
// «до двери» дороже «до ПВЗ» на полторы-две сотни (см. lib/delivery-price.js).
// id вариантов (`pvz`, `courier`) уходят в заказ так же, как id перевозчика, —
// менять их нельзя. Названия у перевозчиков разные: у OZON пункт выдачи может
// быть и постаматом, и покупателю это надо сказать его словами.
const MODES_CDEK = [
  { id: 'pvz', name: 'В пункт выдачи', hint: 'Заберёте сами в офисе СДЭК' },
  { id: 'courier', name: 'Курьером до двери', hint: 'Привезут по указанному адресу' }
];
const MODES_OZON = [
  { id: 'pvz', name: 'В пункт выдачи или постамат', hint: 'Заберёте сами в пункте OZON' },
  { id: 'courier', name: 'Курьером до двери', hint: 'Привезут по указанному адресу' }
];
const METHODS = [
  { id: 'cdek', name: 'СДЭК', hint: 'Курьером до двери или в пункт выдачи', modes: MODES_CDEK },
  { id: 'ozon', name: 'OZON', hint: 'В пункт выдачи или постамат OZON', modes: MODES_OZON }
];

function find(id) {
  const key = String(id == null ? '' : id);
  return METHODS.find(m => m.id === key) || null;
}
function isValid(id) { return !!find(id); }
// Название для панелей и Telegram. Неизвестный id (или заказ без доставки —
// такими остались все прежние заявки) даёт пустую строку, а не «undefined».
function nameOf(id) { const m = find(id); return m ? m.name : ''; }

// Варианты доставки конкретного перевозчика. Неизвестный перевозчик — пустой
// список, а не исключение: список рисуется и на заказе, способ которого уже
// сняли с витрины.
function modesOf(id) { const m = find(id); return m ? m.modes : []; }
function findMode(id, modeId) {
  const key = String(modeId == null ? '' : modeId);
  return modesOf(id).find(x => x.id === key) || null;
}
function isValidMode(id, modeId) { return !!findMode(id, modeId); }
// Короткая подпись для панелей и Telegram: «OZON, курьером». Полное название
// («В пункт выдачи или постамат») там заняло бы половину строки списка, а на
// витрине оно и так приходит вместе со списком вариантов.
//
// Первым в списке всегда идёт пункт выдачи: он дешевле, и витрина выбирает
// заранее именно первый вариант.
function shortModeOf(id, modeId) {
  const m = findMode(id, modeId);
  if (!m) return '';
  return m.id === 'courier' ? 'курьером' : 'в пункт выдачи';
}
module.exports = { METHODS, find, isValid, nameOf, modesOf, findMode, isValidMode, shortModeOf };
