'use strict';
/* ========================= Плавающие цены витрины =========================
 *
 * Раз в период (по умолчанию час) цена каждого товара сдвигается вверх на
 * несколько процентов, а в следующий период — на другие несколько. Витрина от
 * этого выглядит живой: покупатель, вернувшийся через день, видит не тот же
 * ценник до рубля, а рынок, который шевелится.
 *
 * ТРИ ПРАВИЛА, ИЗ КОТОРЫХ ВСЁ ОСТАЛЬНОЕ СЛЕДУЕТ.
 *
 * 1. НИКОГДА НИЖЕ ЦЕНЫ ИЗ КАТАЛОГА. Цена владельца — это пол, а не середина
 *    колебания: она закупочная (см. «Цены» в CLAUDE.md), и уйти под неё значит
 *    продавать в убыток. Поэтому разброс задаётся только вверх: [+min%, +max%].
 *
 * 2. ЦЕНА ОБЯЗАНА ОСТАВАТЬСЯ КРАСИВОЙ — 15 990, 16 490, 16 990. Ценник вида
 *    «16 337 ₽» сразу выдаёт, что число посчитала машина, а не поставил
 *    продавец. Отсюда шаг в 500 ₽ с хвостом 990/490 и следствие из него: у
 *    дешёвого товара между двумя красивыми числами разрыв больше, чем весь
 *    разрешённый процент, и такой товар просто не плавает. Так и надо: соврать
 *    о заявленном проценте хуже, чем оставить цену на месте (на каталоге из 48
 *    товаров это три позиции дешевле 8 000 ₽).
 *
 * 3. НИЧЕГО НЕ ХРАНИМ И НЕ ПИШЕМ. Цена — чистая функция от id товара и номера
 *    периода: тот же товар в тот же час стоит одинаково у всех покупателей и на
 *    всех страницах, а после перезапуска процесса — по-прежнему столько же. Ни
 *    cron, ни записи в файл, ни отдельного поля у товара для этого не нужно.
 *    Заодно это единственный способ не разъехаться между карточкой каталога,
 *    страницей товара, корзиной и заказом: все они спрашивают одно и то же.
 *
 * ЗАФИКСИРОВАННАЯ ЦЕНА ПОКУПАТЕЛЯ выходит сама собой: заказ хранит цену каждой
 * позиции (`order.items[].price`) и итог, а страница оплаты берёт сумму из
 * заказа. Оформил — и дальше колебание его не касается. Остаётся стык на самом
 * оформлении: покупатель мог собрать корзину в конце периода, а нажать
 * «Оформить» уже в начале следующего. Для него это выглядело бы как подмена
 * цены под руками, поэтому `/api/order` принимает и цену прошлого периода —
 * см. `previousOf()` ниже.
 *
 * Товар можно исключить (`noPriceFloat` — галочка в форме): у позиции с
 * прайсом поставщика цена бывает выторгована до рубля, и играть с ней нельзя.
 */

const D = require('./discount');
/* Потолок одной покупки принадлежит кассе, и колебание обязано его знать: иначе
 * оно молча убирает товары с витрины. Mac Studio за 239 990 ₽ при потолке в
 * 250 000 ₽ и разбросе до 5% попадает в 251 490 — а товар дороже потолка
 * витрина показывает как «Нет в наличии» (`sellable` в lib/render.js). То есть
 * карточка то продаётся, то нет, и зависит это от часа. Ценник менять можно, а
 * ассортимент — нет.
 *
 * Кольца зависимостей тут нет: `lib/payments.js` о ценах не знает вовсе. */
const PAYMENTS = require('./payments');

// Значения по умолчанию — ровно те, о которых просили: раз в час, плюс 1–5%.
const DEFAULTS = { min: 1, max: 5, minutes: 60 };
// Выше 50% — это уже не колебание, а другая цена. Граница одна на форму
// настроек и на показ: испорченные руками настройки не должны утроить ценник.
const MAX_PCT = 50;
// Реже суток период не имеет смысла (цена перестанет шевелиться вовсе), чаще
// пяти минут — покупатель увидит смену цены прямо на открытой странице.
const MIN_MINUTES = 5;
const MAX_MINUTES = 24 * 60;
// Шаг «красивой» цены и её хвост: 15 990 → 16 490 → 16 990.
const STEP = 500;
const TAIL = 10;

/* Пустое значение — это «не задано», а не ноль. `Number(null)` и `Number('')`
 * дают 0, и без этой проверки настройка, стёртая руками до `null`, молча
 * обнуляла бы верхнюю границу разброса: колебание выглядело бы выключенным при
 * включённой галочке.
 */
function numOr(value, fallback) {
  if (value === null || value === undefined || value === '') return fallback;
  const n = Number(value);
  return Number.isFinite(n) ? n : fallback;
}
function clamp(n, lo, hi) { return Math.min(hi, Math.max(lo, n)); }

/* Настройки колебания в пригодном для счёта виде. Мусор и пустые поля сводятся
 * к значениям по умолчанию, а не выключают функцию и не дают бесконечный
 * разброс: испорченные настройки не должны ни остановить витрину, ни устроить
 * на ней распродажу наоборот. Перевёрнутый диапазон разворачиваем — форма его
 * не сохранит, но настройки правят и руками.
 */
function conf(settings) {
  const s = settings || {};
  let min = clamp(numOr(s.priceFloatMin, DEFAULTS.min), 0, MAX_PCT);
  let max = clamp(numOr(s.priceFloatMax, DEFAULTS.max), 0, MAX_PCT);
  if (min > max) { const t = min; min = max; max = t; }
  return {
    on: !!s.priceFloat,
    min, max,
    minutes: Math.round(clamp(numOr(s.priceFloatMinutes, DEFAULTS.minutes), MIN_MINUTES, MAX_MINUTES))
  };
}

// Участвует ли товар. Поля нет — участвует: так читаются и `catalog.js`, и все
// карточки, созданные до появления галочки.
function floats(product) { return !!product && product.noPriceFloat !== true; }

// Номер периода. Считается от эпохи, а не от «первого запуска», поэтому у двух
// процессов (витрина и любой скрипт) он один и тот же.
function periodOf(at, minutes) { return Math.floor(Number(at) / (minutes * 60000)); }

/* Ровный ГПСЧ от строки — тот же, что раздаёт даты отзывам (lib/review-dates.js).
 * Нужен один разряд случайности на пару «товар + период», зато повторяемый:
 * иначе цена менялась бы на каждой перезагрузке страницы.
 */
function seeded(str) {
  const s = String(str);
  let h = 2166136261;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  h += 0x6d2b79f5;
  let t = h;
  t = Math.imul(t ^ (t >>> 15), t | 1);
  t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
  return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
}

/* Ближайшее «красивое» число в коридоре [lo, hi] — то есть в границах, которые
 * задал владелец процентами. Сначала пробуем округлить сам ориентир, потом —
 * первое красивое число выше нижней границы.
 *
 * Ни то ни другое не влезло — значит красивых чисел в коридоре нет вовсе
 * (дешёвый товар: между 7 490 и 7 990 разрыв в 6,7%, а разрешено 5%), и цена
 * остаётся базовой. Выйти за заявленный процент ради красоты нельзя: процент
 * владелец задал сам, и врать о нём хуже, чем не колебать цену.
 */
function nice(target, lo, hi, base) {
  const round = Math.round((Number(target) + TAIL) / STEP) * STEP - TAIL;
  if (round >= lo && round <= hi) return round;
  const up = Math.ceil((lo + TAIL) / STEP) * STEP - TAIL;
  if (up >= lo && up <= hi) return up;
  return base;
}

/* Самая дорогая ДОПЛАТА, которая помещается в потолок при цене из каталога.
 *
 * Потолок кассы обрезает не только товар целиком, но и каждое значение по
 * отдельности: витрина гасит вариант, выводящий сборку за предел (`overLimit` в
 * lib/render.js), а считает она это, меняя ОДНО измерение — «сборка минус
 * доплата этого ряда плюс доплата кандидата». Значит для сохранения ассортимента
 * важна не сумма самой дорогой сборки, а самая дорогая ОДИНОЧНАЯ доплата,
 * которая при базовой цене ещё влезала.
 *
 * Пока коридор обрезался просто потолком, колебание этого не берегло: у
 * MacBook Pro 14" база 189 990 уходила в 196 990, и одно значение оперативной
 * памяти гасло само собой — покупатель, вернувшийся через час, находил вариант
 * «нет в наличии» там, где час назад он продавался. Товар с витрины при этом не
 * исчезал, поэтому прежняя проверка (`sellable` в любой час) ничего не ловила.
 */
function variantAdds(product) {
  const out = [];
  const push = list => { for (const v of list || []) { const n = Number(v && v.add); if (Number.isFinite(n) && n > 0) out.push(n); } };
  push(product && product.storages);
  for (const g of (product && product.options) || []) push(g && g.values);
  for (const g of (product && product.bands) || []) { push(g && g.options); push(g && g.sizes); }
  return out;
}
/* Считается это одним проходом по вариантам товара и не кэшируется: список
 * доплат короткий (десятки строк даже у часов), а кэш по ссылке на товар здесь
 * был бы прямо опасен — объект переживает правку каталога, и запомненный запас
 * пустил бы цену выше потолка по данным, которых уже нет.
 */
function headroom(product, base, ceiling) {
  if (!(ceiling > 0)) return 0;
  let value = 0;
  for (const add of variantAdds(product)) {
    if (base + add <= ceiling && add > value) value = add;
  }
  return value;
}

/* Цена товара в ТЕКУЩЕМ периоде — БЕЗ скидки промоакции.
 *
 * Это единственная точка входа: карточка каталога, страница товара, корзина и
 * заказ обязаны спрашивать её, а не `D.basePrice()` напрямую, — иначе
 * покупатель увидит одну цену в каталоге и другую в корзине. Скидку от этой
 * цены срезает промокод (`PROMO.priceFor`), и колебание её не касается: процент
 * задан владельцем и от часа не зависит.
 */
function priceOf(product, settings, at) {
  const base = D.basePrice(product);
  const c = conf(settings);
  if (!c.on || !(base > 0) || !floats(product)) return base;
  const bucket = periodOf(at || Date.now(), c.minutes);
  const r = seeded(String((product && product.id) || '') + ':' + bucket);
  const pct = c.min + (c.max - c.min) * r;
  /* Потолок покупки обрезает коридор сверху: дороже него и товар, и отдельная
   * сборка исчезают с витрины, а колебание не вправе этого сделать. Ноль —
   * кассы выключены, потолка нет вовсе.
   *
   * Вычитаем `headroom()`: подниматься можно ровно настолько, чтобы за потолок
   * не вышло ни одно значение, которое помещалось в него при цене из каталога.
   * Верхняя граница при этом никогда не опускается ниже самой базы — доплата,
   * попавшая в `headroom`, по построению влезала вместе с ней.
   */
  const ceiling = PAYMENTS.limits(settings).max;
  let hi = base * (1 + c.max / 100);
  if (ceiling > 0) hi = Math.min(hi, ceiling - headroom(product, base, ceiling));
  return nice(base * (1 + pct / 100), base * (1 + c.min / 100), hi, base);
}

/* Цена ПРОШЛОГО периода — ради стыка на оформлении.
 *
 * Покупатель мог смотреть на цену в 14:59, а нажать «Оформить заказ» в 15:00, и
 * сервер отверг бы заказ как «корзина изменилась». Формально он прав, а по сути
 * это подмена цены под руками: цену человек видел, и она должна за ним
 * держаться до конца оформления. Дальше прошлого периода не отступаем — иначе
 * старая вкладка позволяла бы покупать по цене вчерашнего дня.
 */
function previousOf(product, settings, at) {
  const c = conf(settings);
  if (!c.on) return priceOf(product, settings, at);
  return priceOf(product, settings, (at || Date.now()) - c.minutes * 60000);
}

module.exports = {
  DEFAULTS, MAX_PCT, MIN_MINUTES, MAX_MINUTES, STEP, TAIL,
  conf, floats, periodOf, nice, headroom, priceOf, previousOf
};
