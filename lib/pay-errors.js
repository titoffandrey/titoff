'use strict';
/*
 * Отказы платёжек одним словарём — на обе кассы сразу.
 *
 * Покупатель не должен догадываться, что платёжек у нас две (это прямое
 * требование: он нажимает «оплатить», выбирает способ и получает реквизиты).
 * Значит и слова про отказ обязаны быть одни и те же: если CrocoPAY отвечает
 * «Requisites not found», а MeridianPay — «Нет свободных реквизитов», покупатель
 * увидит одну и ту же нашу фразу, а не два разных перевода одного и того же.
 *
 * Отсюда отдельный модуль, а не таблица внутри провайдера: держи её в
 * lib/crocopay.js — и вторая касса либо потянула бы его за собой (провайдер
 * зависит от провайдера), либо завела свою копию, которая разъедется на первой
 * правке.
 *
 * Строки провайдеров английские у одного и русские у другого, поэтому в одной
 * таблице лежат оба написания. Это не «на всякий случай»: и то и другое реально
 * приходит с живых касс (CrocoPAY — `Requisites not found`, MeridianPay —
 * `Мерчант находится на модерации.`, проверено 23 августа 2026).
 */

/* Коды и то, что по ним видит ПОКУПАТЕЛЬ.
 *
 * Порядок важен — выигрывает первое совпадение, поэтому частное стоит выше
 * общего: `no_requisite` раньше `amount`, иначе «нет реквизитов на эту сумму»
 * уехало бы в «сумму не принял».
 *
 * Главное правило текстов: говорить, ЧТО ДЕЛАТЬ дальше. «Requisites not found»
 * объясняет покупателю ровно ничего, а «выберите другой способ или попробуйте
 * через пару минут» — это инструкция, и она верная: пул реквизитов у каждого
 * способа свой и пополняется.
 */
const RULES = [
  // Касса подтвердила не тот маршрут, который мы просили (CrocoPAY реально
  // отвечал TO_CARD_TRANSGRAN на запрос TO_CARD). Реквизиты не показываем.
  ['route_mismatch', /method_mismatch|currency_mismatch|region_mismatch/i,
    'Касса не подтвердила выбранный российский способ оплаты. Иностранные реквизиты не показаны — выберите другой способ.'],
  // Счёт, который мы не смогли подтвердить: нет будущего срока действия (значит
  // неизвестно, когда реквизит снова станет чужим) либо касса вернула не ту
  // сумму, которую мы просили. И то и другое — повод не показывать реквизиты.
  ['invoice_invalid', /bad_invoice_state|bad_expiry|amount_mismatch/i,
    'Касса вернула счёт, который не удалось подтвердить (срок действия или сумма). Реквизиты не показаны — выберите другой способ.'],
  // Штатный отказ P2P-процессинга, а не поломка: пул карт конечен, и на
  // конкретную сумму свободной может не быть прямо сейчас.
  ['no_requisite', /requisite|реквизит|no_free|свободн\w* (?:карт|счёт|счет)|трейдер/i,
    'Сейчас нет свободных реквизитов для этого способа. Выберите другой способ оплаты или попробуйте через пару минут.'],
  /* Касса отвечает, ключи приняла, а сделки САМОМУ МЕРЧАНТУ пока запрещены:
   * MeridianPay так отвечает всё время модерации (HTTP 400, «Мерчант находится
   * на модерации.»).
   *
   * Это НЕ «способ недоступен», и раньше оно сюда и уезжало — с последствием,
   * которое видно только в панели: владелец читал «способ недоступен» и шёл
   * искать, какой способ включить, хотя не поможет ни один. Другой код нужен
   * ровно за этим — чтобы панель назвала настоящую причину (см. SHORT ниже).
   *
   * Покупателю при этом говорим то же самое, что и про недоступный способ: про
   * нашу модерацию ему знать незачем, а совет один и тот же — выбрать другое.
   */
  ['merchant_off', /модерац|moderation|мерчант\w*\s+(?:наход|заблок|откл|не\s)|merchant\s+(?:is\s+)?(?:under|not|dis|block|suspend)|аккаунт\w*\s+заблок/i,
    'Этот способ оплаты сейчас недоступен — выберите другой.'],
  ['method_unavailable', /payment_option|not enabled|not supported|not available|метод\w* (?:не|недоступ)|недоступ/i,
    'Этот способ оплаты сейчас недоступен — выберите другой.'],
  ['timeout', /timeout|fetch failed|network|abort/i,
    'Платёжный сервис не отвечает. Заказ сохранён; попробуйте ещё раз через минуту.'],
  ['amount', /amount|limit|сумм|лимит/i,
    'Платёжный сервис не принял эту сумму — менеджер свяжется с вами и поможет с оплатой.']
];

const FALLBACK = 'Не удалось выставить счёт. Выберите другой способ оплаты или попробуйте позже — заказ уже сохранён.';

// Строка провайдера (или уже наш код) -> код. Незнакомое остаётся
// `provider_error`: выдумывать причину по чужому тексту нельзя.
function codeOf(error) {
  const text = String(error == null ? '' : error);
  for (const [code, re] of RULES) if (text === code || re.test(text)) return code;
  return 'provider_error';
}

// Код (или сырая строка провайдера) -> фраза покупателю.
function messageOf(error) {
  const text = String(error == null ? '' : error);
  for (const [code, re, message] of RULES) if (text === code || re.test(text)) return message;
  return FALLBACK;
}

/* Те же коды, но подписью для ПАНЕЛИ — коротко и по делу.
 *
 * Покупателю нужен совет («выберите другой способ»), а менеджеру — причина в
 * два слова, чтобы она встала в строку статистики рядом с числом. Поэтому
 * таблицы две, а не одна на оба случая.
 */
const SHORT = {
  no_requisite: 'нет свободных реквизитов',
  timeout: 'касса не ответила',
  // Единственная строка словаря, где панель и витрина говорят РАЗНОЕ, и разница
  // тут по делу: покупателю нужен совет, а владельцу — правда о том, что менять
  // способы бесполезно, пока касса не допустит мерчанта к сделкам.
  merchant_off: 'мерчант не допущен к сделкам',
  method_unavailable: 'способ недоступен',
  route_mismatch: 'подменила маршрут',
  invoice_invalid: 'счёт не подтверждён',
  amount: 'не приняла сумму',
  provider_error: 'другая ошибка'
};
function shortOf(code) {
  const key = String(code == null ? '' : code).trim();
  return SHORT[key] || key || 'другая ошибка';
}

module.exports = { codeOf, messageOf, shortOf };
