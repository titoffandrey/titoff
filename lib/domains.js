'use strict';
/*
 * Домены, по которым открывается магазин.
 *
 * Магазин по-прежнему ОДИН, и приложение имя сайта не разбирает: витрина,
 * цены и заказы от домена не зависят вовсе. Здесь решается единственный
 * вопрос — какие имена магазин признаёт своими, чтобы прокси выпустил на них
 * сертификат. Это не возврат мультидоменности (той, где у каждого домена были
 * свои цены и своя видимость товаров): все имена ведут на одну и ту же
 * витрину, и различить их изнутри нельзя.
 *
 * ЗАЧЕМ ЭТО ПОЯВИЛОСЬ. 2 сентября 2026 регистратор снял основной домен из зоны
 * `.com` за неподтверждённую whois-верификацию, и витрина стала недоступна
 * целиком — при живом сервере и работающем приложении. Запасной домен тогда
 * поднимали руками: правкой `/etc/caddy/Caddyfile` по SSH через Tor. Делать
 * это в момент, когда магазин уже лежит, — худшее время для работы с
 * конфигом прокси, поэтому привязка переехала в панель.
 *
 * КАК ЭТО РАБОТАЕТ. Caddy умеет выпускать сертификат по требованию (on-demand
 * TLS) и перед каждым выпуском спрашивает у приложения: «это ваш домен?» —
 * обычным HTTP-запросом на петлю. Отвечает `/internal/tls-ask` в `server.js`,
 * а список для ответа даёт этот модуль. Поэтому добавление домена в панели
 * ничего не правит на диске сервера и не требует ни sudo, ни перезапуска
 * Caddy: следующее же обращение к новому имени получит свой сертификат.
 *
 * Основной домен при этом остаётся отдельным блоком в Caddyfile — тем, что
 * прописывает `deploy/setup-server.sh`. Это осознанно: если приложение лежит,
 * `ask` не отвечает, и новые сертификаты не выпускаются вовсе — оставить на
 * этом пути ГЛАВНЫЙ адрес магазина значило бы связать доступность витрины с
 * доступностью того самого процесса, который она и обслуживает.
 */

/* Сколько имён можно привязать. Предел не технический, а смысловой: домены
 * заводят про запас и на случай приостановки, а список из сотни имён на одной
 * витрине — это уже не запас, а чужой трафик, который кто-то направил на нас. */
const MAX = 20;

/* Имя, а не строка — то же правило и та же форма, что в `deploy/setup-server.sh`.
 * Проверка нужна не ради красоты: домен уезжает в ответ прокси, а оттуда — в
 * запрос сертификата у Let's Encrypt. */
const LABEL = '[a-z0-9](?:[a-z0-9-]*[a-z0-9])?';
const NAME = new RegExp(`^${LABEL}(?:\\.${LABEL})+$`);

/* Из того, что вписал человек, делаем имя.
 *
 * Владелец копирует домен из адресной строки, поэтому приходит и `https://`,
 * и хвост пути, и порт, и заглавные буквы. Всё это снимается молча: отказывать
 * из-за протокола, который сам браузер и дописал, — придирка.
 *
 * `www.` тоже снимается: он не отдельный домен, а приставка, и обслуживается
 * вместе с основным именем (`allows` ниже). Иначе владелец добавлял бы каждое
 * имя дважды и всё равно забывал половину.
 */
function clean(value) {
  return String(value == null ? '' : value)
    .trim()
    .toLowerCase()
    .replace(/^[a-z][a-z0-9+.-]*:\/\//, '')  // схема
    .replace(/^[^/@]*@/, '')                 // логин, если скопировали вместе с ним
    .replace(/[/?#].*$/, '')                 // путь, запрос, якорь
    .replace(/:\d+$/, '')                    // порт
    .replace(/\.+$/, '')                     // корневая точка
    .replace(/^www\./, '');
}

/* Похоже ли это на доменное имя. Длины взяты из самого формата: 253 знака на
 * имя целиком и 63 на каждую метку между точками.
 *
 * IP-адрес имени формально не противоречит (цифры и точки), но доменом не
 * является: сертификат на адрес по нашему пути не выпустится вовсе, а строка
 * «89.125.187.83» в списке доменов читалась бы как рабочая привязка. Отсекаем
 * по последней метке — числового домена верхнего уровня не бывает.
 */
function valid(name) {
  const s = String(name || '');
  if (!s || s.length > 253 || !NAME.test(s)) return false;
  const labels = s.split('.');
  if (/^\d+$/.test(labels[labels.length - 1])) return false;
  return labels.every(label => label.length <= 63);
}

/* Разбор поля формы: по домену на строку.
 *
 * Возвращает и годные имена, и мусор отдельно — форма обязана СКАЗАТЬ, что
 * именно не так, а не молча выбросить строку (то же правило, что у цен
 * вариантов и реквизитов продавца). Дубли схлопываются: `example.com` и
 * `https://WWW.Example.com/` — одно и то же имя.
 *
 * Негодной считается СТРОКА ЦЕЛИКОМ, а не отдельное слово в ней, хотя внутри
 * строки имена и разделяются пробелом с запятой. Иначе на «не домен!» форма
 * жаловалась бы на «не» — владелец искал бы в поле строку, которой там нет.
 */
function parse(text) {
  const list = [];
  const bad = [];
  const raw = Array.isArray(text) ? text.join('\n') : String(text == null ? '' : text);
  for (const line of raw.split(/[\r\n]+/)) {
    const source = line.trim();
    if (!source) continue;
    const names = source.split(/[\s,;]+/).filter(Boolean).map(clean).filter(Boolean);
    if (!names.length || !names.every(valid)) {
      if (!bad.includes(source)) bad.push(source);
      continue;
    }
    for (const name of names) if (!list.includes(name)) list.push(name);
  }
  return { list, bad };
}

/* Привязанные домены. Читается из настроек, поэтому чинить порченое значение
 * приходится здесь: правку руками в `settings.json` никто не отменял, а
 * витрина из-за неё падать не должна. */
function list(settings) {
  const saved = settings && settings.siteDomains;
  const source = Array.isArray(saved) ? saved : [];
  const out = [];
  for (const item of source) {
    const name = clean(item);
    if (valid(name) && !out.includes(name)) out.push(name);
  }
  return out.slice(0, MAX);
}

/* Наш ли это домен. Спрашивает прокси перед выпуском сертификата, поэтому
 * ответ обязан быть точным: лишнее «да» — это сертификат на чужое имя,
 * выписанный за наш счёт и на наши лимиты у Let's Encrypt.
 *
 * `www.` засчитывается вместе с основным именем: прокси уводит его редиректом
 * на домен без приставки, но сертификат для этого всё равно нужен свой.
 */
function allows(settings, host) {
  const name = clean(host);
  if (!valid(name)) return false;
  return list(settings).includes(name);
}

module.exports = { MAX, clean, valid, parse, list, allows };
