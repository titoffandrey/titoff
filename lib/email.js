'use strict';
/* Адрес электронной почты: одна форма хранения и одна проверка на весь проект.
 *
 * Спрашивают её трое — заказ (`email` в lib/db.js), личный кабинет
 * (lib/customers.js) и отправка писем (lib/mail.js), — и порознь они разошлись
 * бы на первой же правке: заказ принял бы адрес, под который кабинет потом не
 * заведётся. Модуль нарочно без зависимостей: его требует и lib/db.js, и те,
 * кто требует lib/db.js, — кольцо здесь замкнулось бы первым.
 *
 * Хранится адрес в нижнем регистре и без пробелов по краям: «Ivan@Mail.ru» и
 * «ivan@mail.ru» — один и тот же ящик, и два написания читались бы как два
 * разных покупателя. Проверка нарочно грубая — та же, что у почты магазина в
 * настройках: адрес должен ВЫГЛЯДЕТЬ адресом, а не быть доказанно существующим.
 * Ложный отказ на оформлении дороже пропущенной опечатки: пароль от кабинета
 * на такой адрес просто не дойдёт, а заказ при этом оформится.
 */
const RE = /^[^\s@]+@[^\s@.]+\.[^\s@]{2,}$/;
const MAX = 120;

function norm(value) {
  return String(value == null ? '' : value).trim().toLowerCase().slice(0, MAX);
}
// Нормализованный адрес либо пустая строка, если это не адрес.
function valid(value) {
  const email = norm(value);
  // Перевод строки в адресе — это заголовок письма, подделанный из формы.
  return RE.test(email) && !/[\r\n<>]/.test(email) ? email : '';
}

module.exports = { RE, MAX, norm, valid };
