/* Слова, после которых идёт название улицы, а не города. Само слово и следующее
 * за ним выбрасываются: иначе «Новосибирск, ул. Кирова» уехал бы в Поволжье —
 * улица Кирова есть в каждом втором городе, а название длиннее «Новосибирска»
 * не бывает только по счастливой случайности.
 *
 * Разделены на два списка не ради порядка: по ним же `lib/address.js` проверяет,
 * что в адресе названы и улица, и дом. Один словарь на оба разбора — иначе они
 * разъедутся, и адрес, прошедший проверку, попадёт в другую зону.
 */
const STREET_MARKERS = [
  'ул', 'улица', 'пр', 'просп', 'проспект', 'пр-кт', 'пр-т', 'пер', 'переулок', 'ш', 'шоссе',
  'наб', 'набережная', 'бул', 'б-р', 'бульвар', 'пл', 'площадь', 'мкр', 'микрорайон', 'проезд',
  'тракт', 'линия', 'аллея', 'туп', 'тупик', 'кв-л', 'квартал', 'снт', 'днп', 'тер'
];
const HOUSE_MARKERS = [
  'д', 'дом', 'вл', 'влд', 'к', 'корп', 'корпус', 'стр', 'строение', 'кв', 'квартира',
  'оф', 'офис', 'под', 'подъезд', 'этаж', 'уч', 'участок', 'пвз', 'постамат'
];
const MARKERS = new Set(STREET_MARKERS.concat(HOUSE_MARKERS));

// Строка адреса к виду, по которому ищем: строчные буквы, ё→е, всё лишнее —
// пробел. Дефис оставляем: он внутри названий («Ростов-на-Дону», «улан-удэ»).
function norm(s) {
  return String(s == null ? '' : s)
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/[^a-zа-я0-9-]+/g, ' ')
    .trim();
}

// Адрес словами — в том же виде, в каком его разбирает зона. Нужен и проверке
// полноты адреса (`lib/address.js`), чтобы разбор был один на двоих.
function words(address) { return norm(address).split(/\s+/).filter(Boolean); }

// Адрес без улиц: маркер и слово за ним выбрасываются.
function placePart(address) {
  const raw = words(address);
  const out = [];
  for (let i = 0; i < raw.length; i++) {
    if (MARKERS.has(raw[i])) { i++; continue; }   // сам маркер и название улицы за ним
    out.push(raw[i]);
  }
  return ' ' + out.join(' ') + ' ';
}

// Сколько букв разрешаем дописать к названию. Русские слова склоняются, а \b в
// JS с кириллицей не работает (см. «Подводные камни» в CLAUDE.md), поэтому
// границу собираем руками: слева не-буква, справа — хвост окончания. Длинным
// основам хвост нужен («свердловск» + «ая»), коротким названиям — почти нет:
// «тула» с тремя буквами хвоста поймала бы «Тулаково».
function tail(pattern) {
  if (pattern.length >= 8) return 3;
  if (pattern.length >= 5) return 2;
  if (pattern.length >= 4) return 1;
  return 0;
}

// Плоский список [регулярка, зона], от длинных названий к коротким: при
// одинаковом месте в строке побеждает длинное, поэтому «нижний новгород»
// проверяется раньше «новгородск», а «ростов-на-дону» — раньше «ростовск».
const RULES = (() => {
  const list = [];
  for (const zone of Object.keys(PLACES)) for (const place of PLACES[zone]) list.push({ place, zone });
  list.sort((a, b) => b.place.length - a.place.length);
  return list.map(x => ({
    zone: x.zone,
    re: new RegExp('(^|[^a-zа-я0-9])' + x.place.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
      + '[а-я]{0,' + tail(x.place) + '}(?=[^a-zа-я0-9]|$)')
  }));
})();

/* Зона по адресу.
 *
 * Побеждает НЕ самое длинное совпадение, а самое РАННЕЕ: и DaData, и обычный
 * ввод начинают с региона и города, а дальше идут улицы, у которых названия
 * такие же («г Москва, Ленинградский пр-кт» — это Москва, а не Ленинградская
 * область). Улицы с маркером уже выброшены, но название бывает и перед ним.
 */
function zoneFor(address) {
  const s = placePart(address);
  if (s.trim().length < 2) return FALLBACK;
  let best = null, at = Infinity;
  for (const r of RULES) {
    const m = r.re.exec(s);
    if (!m) continue;
    if (m.index < at) { at = m.index; best = r.zone; }
    if (at === 0) break;
  }
  return best || FALLBACK;
}

function zone(id) {
  const key = String(id == null ? '' : id);
  return ZONES.find(z => z.id === key) || null;
}
function isValidZone(id) { return !!zone(id); }
function zoneName(id) { const z = zone(id); return z ? z.name : ''; }

module.exports = {
  ZONES, FALLBACK, zoneFor, zone, isValidZone, zoneName,
  // placePart наружу нужен поиску пунктов выдачи (lib/pickup.js): город в адресе
  // он ищет тем же разбором, что и зона, иначе тариф считался бы по одному
  // городу, а пункты предлагались бы в другом.
  STREET_MARKERS, HOUSE_MARKERS, MARKERS, words, placePart
};
