'use strict';
// Способы оплаты кассы CrocoPAY в рублях. Закрытый список, устроенный как
// lib/delivery.js: по нему рисуется выбор на странице оплаты, проверяется
// запрос на создание счёта и подписывается строка в панелях.
//
// Отдельный модуль, а не константа в render.js, потому что список нужен и в
// lib/db.js при нормализации платежа — а db.js рендер подключать не может и не
// должен (render → tenancy → db, вышел бы цикл).
//
// `id` — это `payment_option` платёжки. Он уходит в счёт и остаётся в заказе
// навсегда, поэтому менять их нельзя, только добавлять новые. Название и
// подсказка правятся свободно.
//
// `kind` — что приходит в реквизитах счёта: карта, телефон или ссылка QR. От
// него зависит подпись на странице оплаты, потому что поле `card` у платёжки
// одно на все случаи.
//
// Порядок — порядок показа: СБП первым, он привычнее всего.
const METHODS = [
  { id: 'SBP', name: 'СБП', hint: 'Перевод по номеру телефона, любой банк', kind: 'phone' },
  { id: 'TO_CARD', name: 'Перевод на карту', hint: 'Любой банк России', kind: 'card' },
  { id: 'SBP_TBANK', name: 'СБП · Т-Банк', hint: 'Если платите из Т-Банка', kind: 'phone' },
  { id: 'SBP_ALFA', name: 'СБП · Альфа-Банк', hint: 'Если платите из Альфа-Банка', kind: 'phone' },
  { id: 'QR_NSPK', name: 'QR-код НСПК', hint: 'Ссылка откроется в приложении банка', kind: 'qr' },
  { id: 'TO_CARD_TRANSGRAN', name: 'Карта · трансграничный', hint: 'Для карт иностранных банков', kind: 'card' },
  { id: 'SBP_TRANSGRAN', name: 'СБП · трансграничный', hint: 'Для карт иностранных банков', kind: 'phone' },
  { id: 'TRANSGRAN_SBER', name: 'SberPay · трансграничный', hint: 'Перевод по номеру телефона', kind: 'phone' },
  { id: 'TRANSGRAN_ALFA', name: 'Альфа-Банк · трансграничный', hint: 'Карта или номер телефона', kind: 'card' },
  { id: 'TRANSGRAN_VTB', name: 'ВТБ · трансграничный', hint: 'Карта или номер телефона', kind: 'card' },
  { id: 'TRANSGRAN_TPAY', name: 'TPay · трансграничный', hint: 'Карта или номер телефона', kind: 'card' },
  // Этого способа нет в таблице документации, но он реально включён у кассы
  // (проверено 17 августа 2026). Не вписав его сюда, мы бы его просто прятали:
  // показываем пересечение, а незнакомый код в пересечение не попадает.
  { id: 'TRANSGRANCARD_TJS', name: 'Карта Таджикистана', hint: 'Трансграничный перевод на карту', kind: 'card' }
];

function find(id) {
  const key = String(id == null ? '' : id).trim();
  return METHODS.find(m => m.id === key) || null;
}
function isValid(id) { return !!find(id); }
// Название для панелей и страницы оплаты. Неизвестный id (или платёж без
// способа — такими остались все прежние заявки) даёт пустую строку, а не
// «undefined».
function nameOf(id) { const m = find(id); return m ? m.name : ''; }
// Подпись реквизита зависит от того, что именно прислала платёжка в поле `card`.
function requisiteLabel(id) {
  const m = find(id);
  if (!m) return 'Реквизиты';
  if (m.kind === 'phone') return 'Номер телефона';
  if (m.kind === 'qr') return 'Ссылка для оплаты';
  return 'Номер карты';
}

// Пересечение нашего списка с тем, что реально включено у кассы.
//
// `null` — касса не ответила: показываем весь список, потому что без него
// покупателю нечем платить вовсе, а несовпадение поймает сама касса при
// создании счёта и вернёт понятную ошибку.
//
// Пустой массив — касса ответила, и способов у неё нет. Это НЕ то же самое:
// показать одиннадцать заведомо нерабочих кнопок хуже, чем честно сказать, что
// оплатить сейчас нечем.
function allowed(options) {
  if (!Array.isArray(options)) return METHODS.slice();
  return METHODS.filter(m => options.includes(m.id));
}

module.exports = { METHODS, find, isValid, nameOf, requisiteLabel, allowed };
