'use strict';
/* ==================== Ответ консультанта печатается, а не падает ====================
 *
 * Модель отвечает быстрее человека: первые слова приходят через полсекунды, а
 * весь ответ — за пару. В окне это выглядит так, будто на том конце не пишут, а
 * подставляют заранее готовый текст, — то есть ровно тем, чем оно и является.
 * Покупателю от этого неуютно: он задал живой вопрос и получил машинную выдачу.
 *
 * Здесь ответ проходит через задержку и ровный темп. Двух частей достаточно,
 * чтобы разговор читался как разговор:
 *
 *   1. ПАУЗА ПЕРЕД НАЧАЛОМ — «прочитал вопрос и взялся отвечать». Считается по
 *      длине ВОПРОСА: на «а 512 есть?» человек отвечает быстрее, чем на абзац с
 *      тремя условиями сразу.
 *   2. ТЕМП ПЕЧАТИ — по длине ОТВЕТА. Длинный ответ и печатается дольше, как у
 *      живого человека.
 *
 * ГЛАВНОЕ ОГРАНИЧЕНИЕ — ВЕРХНИЙ ПРЕДЕЛ, и он тут не для красоты. Скорость
 * первого ответа — то, ради чего чат на витрине вообще стоит: каждая секунда
 * молчания это шанс, что покупатель закроет вкладку (см. шапку public/chat.js).
 * Поэтому пауза не длиннее `THINK_MAX`, а вся печать — не длиннее `TYPE_MAX`,
 * какой бы длины ни вышел ответ. Настоящий человек печатал бы абзац полминуты;
 * магазину столько молчать нельзя.
 *
 * Пауза и печать ощущаются по-разному, и предел у них поэтому разный. Пауза —
 * это ожидание в чистом виде, её терпят секунду-полторы. Печать ожиданием не
 * ощущается вовсе: текст уже идёт, его читают по мере появления, — поэтому ей
 * отведено втрое больше.
 *
 * Модуль ничего не знает ни о чате, ни о модели: на вход — куски текста, на
 * выход — вызовы `send`. Так его можно проверить временем, не поднимая ни
 * диалога, ни OpenAI.
 */

// Как часто отдаём накопленное. Реже — печать становится рваной, чаще — растёт
// число сообщений в живом канале ни за чем: 90 мс это 11 порций в секунду, а
// глаз всё равно читает медленнее.
const TICK = 90;

/* Темп печати: миллисекунд на знак. 16 мс — это около 62 знаков в секунду,
 * быстрая печать в мессенджере (примерно 750 знаков в минуту). Медленнее было
 * бы честнее по-человечески, но магазин не может заставлять ждать ответа
 * полминуты. */
const MS_PER_CHAR = 16;
const TYPE_MIN = 500;    // даже «Да, есть» не выпаливаем мгновенно
const TYPE_MAX = 3000;   // потолок печати: дальше это уже не «пишет», а «молчит»

/* Пауза перед первым словом. Она и есть то самое «через пару секунд»: короткий
 * вопрос — короче пауза. Ниже THINK_MIN опускаться незачем (пропадает сам
 * эффект), выше THINK_MAX нельзя (это чистое ожидание). */
const THINK_BASE = 450;
const THINK_PER_CHAR = 9;
const THINK_MIN = 700;
const THINK_MAX = 1800;

function clamp(n, lo, hi) { return Math.min(hi, Math.max(lo, n)); }

// Сколько «читаем» вопрос перед тем, как начать отвечать.
function thinkDelay(ask) {
  const len = String(ask == null ? '' : ask).length;
  return Math.round(clamp(THINK_BASE + len * THINK_PER_CHAR, THINK_MIN, THINK_MAX));
}

// Сколько всего печатается ответ известной длины.
function typeDuration(len) {
  return Math.round(clamp((Number(len) || 0) * MS_PER_CHAR, TYPE_MIN, TYPE_MAX));
}

/* Начать печатать.
 *
 *   opts.ask   — вопрос покупателя: по его длине считается пауза;
 *   opts.send  — куда отдавать куски (в чате это `CHAT.push(id, 'delta', …)`);
 *   opts.alive — «продолжать ли»: в диалог мог войти оператор, и допечатывать
 *                поверх живого человека нельзя.
 *
 * Возвращает: `feed(piece)` — кусок от модели, `finish()` — обещание, которое
 * исполнится, когда всё напечатано (и не раньше конца паузы, даже если печатать
 * оказалось нечего), `sent()` — что покупатель РЕАЛЬНО увидел.
 */
function start(opts) {
  const o = opts || {};
  const send = typeof o.send === 'function' ? o.send : function () {};
  const alive = typeof o.alive === 'function' ? o.alive : function () { return true; };
  const now = typeof o.now === 'function' ? o.now : Date.now;
  const startAt = now() + thinkDelay(o.ask);

  let queue = '';        // что пришло от модели, но ещё не показано
  let shown = '';        // что покупатель уже увидел
  let fed = false;       // модель закончила (или оборвалась)
  let closed = false;    // работа завершена: очередь пуста либо нас остановили
  let timer = null;
  let waiting = null;    // промис finish(), пока он не исполнен

  function stop() {
    if (timer) { clearInterval(timer); timer = null; }
    closed = true;
    if (waiting) { const done = waiting; waiting = null; done(); }
  }

  function tick() {
    const at = now();
    // Пауза «читаю вопрос» ещё идёт — не показываем ничего, даже если модель
    // уже всё прислала.
    if (at < startAt) return;
    if (!alive()) return stop();
    if (!queue.length) {
      // Печатать нечего: модель закончила — закончили и мы, иначе ждём куски.
      if (fed) stop();
      return;
    }
    /* Сколько знаков отдать сейчас. Срок окончания пересчитываем на каждом
     * такте от ВСЕЙ известной длины ответа: пока модель печатает, длина растёт,
     * и вместе с ней отодвигается конец — темп при этом остаётся ровным, без
     * рывков «догоняем накопленное». */
    const total = shown.length + queue.length;
    const endBy = startAt + typeDuration(total);
    const left = Math.max(TICK, endBy - at);
    const chars = Math.max(1, Math.ceil(queue.length * TICK / left));
    const piece = queue.slice(0, chars);
    queue = queue.slice(piece.length);
    shown += piece;
    try { send(piece); } catch (e) { /* оборванный канал печать не роняет */ }
    if (!queue.length && fed) stop();
  }

  /* Таймер обычный, БЕЗ `unref()`. Соблазн был: печать живёт секунды, и держать
   * ею процесс кажется лишним. Но на `finish()` висит обещание, и с открепленным
   * таймером оно просто не исполнилось бы, останься в петле событий больше
   * ничего, — то есть ответ повис бы навсегда. Несколько секунд на завершении
   * процесса дешевле такой ловушки. */
  timer = setInterval(tick, TICK);

  return {
    feed(piece) {
      if (closed) return;
      queue += String(piece == null ? '' : piece);
    },
    // Модель закончила. Ждём, пока допечатается остаток, — и в любом случае не
    // раньше конца паузы: иначе ответ, которого не случилось, приходил бы
    // мгновенно и выдавал автоматику с головой.
    finish() {
      fed = true;
      if (closed) return Promise.resolve(shown);
      return new Promise(resolve => {
        waiting = () => resolve(shown);
        // Очередь могла опустеть ещё до `finish()`, и следующий такт закроет
        // работу сам. Отдельной проверки здесь не нужно: `tick` идёт постоянно.
      });
    },
    // Что покупатель увидел на самом деле. Нужно ровно на одном пути: оператор
    // вошёл в разговор посреди ответа, печать остановлена — и сохранить надо
    // напечатанное, а не весь текст модели, иначе человек и панель увидят
    // разные разговоры.
    sent() { return shown; },
    stop
  };
}

module.exports = {
  TICK, MS_PER_CHAR, TYPE_MIN, TYPE_MAX, THINK_MIN, THINK_MAX,
  thinkDelay, typeDuration, start
};
