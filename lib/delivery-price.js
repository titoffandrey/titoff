'use strict';
/* ========================= Цена доставки: своя сетка тарифов =========================
 * Считаем сами, без обращения к перевозчикам: внешних зависимостей у проекта нет,
 * а калькуляторы СДЭК и OZON требуют договора, ключей и живой сети на каждом
 * открытии оформления. Поэтому здесь своя сетка, собранная по официальным
 * тарифам обоих перевозчиков (август 2026).
 *
 * За что считаем: посылка «две коробки телефона» — около 2 кг фактических и
 * примерно столько же объёмных (30×20×15 см), отправка ВСЕГДА из Москвы. Это
 * средний заказ витрины; крупная техника (Mac, монитор) дороже потолка одной
 * покупки и не продаётся вовсе (см. «Пределы одной покупки» в CLAUDE.md).
 *
 * Откуда числа:
 *   - СДЭК до ПВЗ: опубликованная вилка «Посылка» — Москва→Петербург 200–280 ₽
 *     за 1 кг и 360–490 ₽ за 5 кг, Москва→Екатеринбург 320–440 и 490–640,
 *     Москва→Новосибирск 400–520 и 600–780. Берём середину вилки и линейно
 *     переносим на 2 кг — получается 290, 430 и 520 ₽; остальные зоны
 *     расставлены между ними по удалённости.
 *   - СДЭК курьером: та же публикация даёт «до двери дороже на 150–250 ₽».
 *     Ближние зоны у нижней границы, дальние — у верхней.
 *   - OZON: собственная отправка посылок начинается с 49 ₽, а Москва→Владивосток
 *     стоит около 1700 ₽ за габаритную коробку. Наша посылка мелкая, поэтому по
 *     всем зонам OZON выходит заметно дешевле СДЭК — так оно у них и есть.
 *
 * Тариф — коммерческое решение, а не факт: числа правятся здесь, в одном месте.
 * Сетка обязана быть полной (все зоны у каждого способа и варианта) — это
 * закреплено тестом.
 */

const Z = require('./delivery-zones');
const DELIVERY = require('./delivery');

// [способ][вариант][зона] — цена в рублях за нашу среднюю посылку.
const RATES = {
  cdek: {
    pvz: { msk: 210, cfo: 260, szfo: 290, pfo: 360, yug: 380, ural: 430, sfo: 520, dfo: 700, ru: 450 },
    courier: { msk: 360, cfo: 440, szfo: 470, pfo: 550, yug: 580, ural: 650, sfo: 760, dfo: 980, ru: 670 }
  },
  ozon: {
    pvz: { msk: 150, cfo: 200, szfo: 230, pfo: 270, yug: 290, ural: 330, sfo: 390, dfo: 550, ru: 350 },
    courier: { msk: 300, cfo: 350, szfo: 380, pfo: 420, yug: 450, ural: 490, sfo: 550, dfo: 750, ru: 520 }
  }
};

// Тариф по сетке. Неизвестный способ, вариант или зона — 0: цену выдумывать
// нельзя, а вызывающий такой заказ и не примет.
function rate(method, mode, zoneId) {
  const byMode = RATES[String(method || '')];
  const byZone = byMode && byMode[String(mode || '')];
  const price = byZone && byZone[String(zoneId || '')];
  return Number.isFinite(price) ? price : 0;
}

/* ------------------------- Округление итоговой суммы -------------------------
 * Покупателю выставляется одна сумма — товары плюс доставка, — и она должна
 * читаться как цена, а не как результат деления. Поэтому доставку двигаем в
 * пределах небольшого окна вокруг тарифа так, чтобы ИТОГ лёг на круглое число:
 * сначала пробуем тысячи, потом полтысячи, потом сотни.
 *
 * Двигаем именно доставку, а не цену товара: цена товара — это то, что
 * покупатель видел в каталоге и запомнил, а стоимость доставки у перевозчика и
 * так плавает от габаритов и пункта выдачи.
 *
 * Окно несимметричное — вверх шире, чем вниз: тариф из сетки средний, и уйти
 * заметно ниже него значит доплатить перевозчику из своего кармана. Небольшой
 * недобор — 60 ₽ или 15 % тарифа, что больше, — разрешён: без хода вниз итог
 * пришлось бы тянуть до следующей сотни вверх, а это дороже для покупателя.
 */
const STEPS = [1000, 500, 100];

function round10(n) { return Math.round(n / 10) * 10; }

// Границы окна. Ширина всегда больше 100 ₽, поэтому шаг «сотни» найдёт
// подходящую сумму при любом тарифе — до сотен итог округляется всегда.
function priceWindow(base) {
  const lo = Math.max(50, round10(base - Math.max(60, base * 0.15)));
  const hi = round10(base + Math.max(140, base * 0.25));
  return { lo, hi: Math.max(hi, lo + 150) };
}

/* Подобрать стоимость доставки под сумму товаров.
 * Возвращает число рублей: сумма `goods + price` кратна 1000, 500 или 100 —
 * первому шагу, для которого нашлось значение внутри окна. Из нескольких
 * подходящих берём ближайшее к тарифу.
 *
 * Потолок одной покупки соблюдаем и здесь: округлять вверх до суммы, которую
 * касса не проведёт, — значит собрать заказ, который нельзя оплатить.
 */
function fit(goods, base, min, ceiling) {
  const sum = Number(goods);
  const tariff = Number(base);
  const floor = Number(min) > 0 ? Number(min) : 0;
  if (!Number.isFinite(tariff) || tariff <= 0) return 0;
  if (!Number.isFinite(sum) || sum <= 0) return Math.max(round10(tariff), floor);
  const { lo, hi } = priceWindow(tariff);
  // Потолок приходит СНАРУЖИ, а не берётся константой: владелец меняет диапазон
  // заказа в настройках, и подгонка обязана двигать цену в тех же границах —
  // иначе доставка округлила бы итог до суммы, которую касса уже не проведёт.
  // Ноль означает «потолка нет» (оплата на витрине выключена).
  const max = Number(ceiling) > 0 ? Number(ceiling) : 0;
  for (const step of STEPS) {
    let best = null;
    const from = Math.ceil((sum + lo) / step) * step;
    for (let total = from; total <= sum + hi; total += step) {
      if (max && total > max) break;
      const price = total - sum;
      if (price < lo || price <= floor) continue;
      if (best === null || Math.abs(price - tariff) < Math.abs(best - tariff)) best = price;
    }
    if (best !== null) return best;
  }
  return Math.max(round10(tariff), floor);   // до потолка не дотянулись — берём тариф как есть
}

/* Расчёт одного способа — для /api/order.
 * Считается через `quoteAll`, а не отдельной формулой: цена зависит не только от
 * своего тарифа, но и от соседнего варианта (курьер обязан выйти дороже ПВЗ), и
 * посчитанная в обход этого цифра разошлась бы с показанной на витрине.
 *
 * `goods` — сумма товаров; при нуле (корзина ещё не собрана) отдаём чистый тариф.
 * Неизвестный способ или вариант — `ok: false` и нулевая цена: заказ с такой
 * доставкой всё равно не принимается.
 */
function quote(method, mode, address, goods, ceiling) {
  const all = quoteAll(address, goods, ceiling);
  const byMode = all.prices[String(method == null ? '' : method)] || null;
  const price = byMode ? byMode[String(mode == null ? '' : mode)] : undefined;
  const sum = Number(goods) > 0 ? Number(goods) : 0;
  const ok = typeof price === 'number' && price > 0;
  return {
    ok,
    zone: all.zone,
    zoneName: all.zoneName,
    base: rate(method, mode, all.zone),
    price: ok ? price : 0,
    total: sum + (ok ? price : 0)
  };
}

/* Цены сразу всех способов и вариантов по одному адресу.
 * Витрине нужна не одна цифра, а все четыре: покупатель должен видеть, во что
 * ему обойдётся курьер, ДО того как выберет его. Считается это локально — по
 * таблице, без единого внешнего запроса, — поэтому отдать все дешевле, чем
 * ходить на сервер при каждом переключении.
 */
function quoteAll(address, goods, ceiling) {
  const zoneId = Z.zoneFor(address);
  const prices = {};
  for (const m of DELIVERY.METHODS) {
    prices[m.id] = {};
    // Варианты считаются по порядку, и каждый следующий обязан выйти дороже
    // предыдущего: в списке они идут от дешёвого к дорогому (пункт выдачи, потом
    // курьер), а подгонка под круглый итог двигает цены и способна сделать
    // курьера не дороже ПВЗ — рядом в одном ряду это читалось бы как ошибка.
    let floor = 0;
    for (const mode of m.modes) {
      const price = fit(goods, rate(m.id, mode.id, zoneId), floor, ceiling);
      prices[m.id][mode.id] = price;
      floor = price;
    }
  }
  return { zone: zoneId, zoneName: Z.zoneName(zoneId), prices };
}

module.exports = { RATES, STEPS, rate, fit, quote, quoteAll, priceWindow };
