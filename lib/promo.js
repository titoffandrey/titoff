'use strict';
/* ============================== Промокоды ==============================
 *
 * ГЛАВНОЕ ПРАВИЛО, ИЗ КОТОРОГО СЛЕДУЕТ ВСЁ ОСТАЛЬНОЕ: скидка товара
 * («промоакция» на карточке) И ЕСТЬ скидка промокода. В карточке товара лежит
 * ПОЛНАЯ цена, а процент от неё срезает код, применённый по умолчанию: витрина
 * показывает цену с уже применённым кодом, а на оформлении его видно строкой —
 * с кодом, выгодой и кнопкой «Удалить». Убрал код — платит полную цену, ту
 * самую, что зачёркнута. Выключили промоакцию — то же самое у всех разом.
 *
 * Отсюда два вида кодов, и различаются они одним числом:
 *
 *   - `percent: 0` — СКИДКА ТОВАРА: у каждого товара свой процент, тот, что
 *     задан в его карточке. Такой код и применяется по умолчанию: ценник
 *     витрины показан уже с ним;
 *   - `percent: 20` — СВОЙ ПРОЦЕНТ на все товары, от той же полной цены. Это код
 *     для конкретного покупателя: он вводит его руками на оформлении.
 *
 * ПОЧЕМУ КОДОМ ПО УМОЛЧАНИЮ МОЖЕТ БЫТЬ ТОЛЬКО «СКИДКА ТОВАРА». Цены каталога
 * закупочные и скидка у каждого товара своя (см. «Цены» в CLAUDE.md), а карточка
 * и корзина обязаны показывать одно и то же число. Код со своим процентом,
 * применённый ко всем сразу, переписал бы каждую цену в каталоге — и у товара со
 * скидкой в 30% «общие −20%» оказались бы ДОРОЖЕ его же ценника. Поэтому
 * автоматически применяется только код со скидкой товара, а свой процент
 * покупатель вводит сам — ровно как в любом магазине.
 *
 * НИКОГДА НЕ ДОРОЖЕ ЦЕННИКА. Код со своим процентом меньше скидки товара всё
 * равно не поднимает цену: покупатель, применивший законный код и увидевший
 * итог БОЛЬШЕ прежнего, читает это как обман. Такой код просто ничего не меняет
 * (`Math.min` в `priceFor`).
 *
 * СИСТЕМА ВЫКЛЮЧЕНА — СКИДКИ НЕТ НИ У КОГО. Покупатель платит цену из карточки
 * товара, а с витрины уходят плашка, зачёркнутая цена и процент: скидку даёт
 * код, и без него обещать её не от чьего имени. Прежде скидка была «зашита» в
 * сам ценник, и выключенная акция ничего не меняла — то есть акция, которой
 * нет, продолжала действовать. Закреплено тестом.
 *
 * Считается всё в одном месте — `priceFor()`: её спрашивают и `/api/cart`, и
 * `/api/order`. Второй расчёт цены разошёлся бы с первым на первой же правке, а
 * увидеть это можно только глазами.
 */

const D = require('./discount');

// Больше полусотни кодов — это уже не «промокод для клиента», а справочник, и
// хранить его в настройках магазина незачем.
const MAX_CODES = 50;
const CODE_MAX = 24;
/* Код набирают руками с телефона, поэтому только латиница, цифры, дефис и
 * подчёркивание: кириллическая «С» неотличима от латинской, и владелец потом
 * полдня выясняет, почему «СКИДКА» не срабатывает. */
const CODE_RE = /^[A-Z0-9][A-Z0-9_-]{1,23}$/;

// Код приводится к верхнему регистру ВЕЗДЕ: и при сохранении, и при сверке.
// «sale» с витрины и «SALE» из панели — один и тот же код.
function normCode(value) {
  return String(value == null ? '' : value).replace(/\s+/g, '').toUpperCase().slice(0, CODE_MAX);
}
function validCode(value) { return CODE_RE.test(normCode(value)); }

/* Процент кода. Ноль — «скидка товара», см. шапку файла; потолок тот же, что у
 * скидки товара (lib/discount.js), и по той же причине: 95% превращают ценник в
 * опечатку. Мусор и пустое поле читаются как ноль — это законное значение, а не
 * ошибка. */
function cleanPercent(value) {
  const n = Number(String(value == null ? '' : value).replace(/\s+/g, '').replace(',', '.'));
  if (!Number.isFinite(n) || n <= 0) return 0;
  return Math.min(D.MAX_PCT, Math.round(n));
}

// Одна запись справочника. Негодный код — `null`: чужая строка в список не
// попадает вовсе, а не оседает там пустым значением.
function cleanEntry(raw) {
  const code = normCode(raw && raw.code);
  if (!validCode(code)) return null;
  return {
    code,
    percent: cleanPercent(raw && raw.percent),
    // Поля нет — код работает: так читаются записи, сделанные до появления
    // выключателя у отдельного кода.
    on: !(raw && raw.on === false),
    // Заметка для владельца. Покупателю не показывается нигде.
    note: String((raw && raw.note) || '').trim().slice(0, 120)
  };
}

// Справочник кодов из настроек: только годные записи, без повторов.
function codes(settings) {
  const list = Array.isArray(settings && settings.promoCodes) ? settings.promoCodes : [];
  const out = [], seen = new Set();
  for (const raw of list.slice(0, MAX_CODES)) {
    const entry = cleanEntry(raw);
    if (!entry || seen.has(entry.code)) continue;
    seen.add(entry.code);
    out.push(entry);
  }
  return out;
}

/* Работает ли система вообще. Галочки мало: без единого включённого кода поле на
 * оформлении спрашивало бы то, чего у магазина нет. */
function enabled(settings) {
  return !!(settings && settings.promoOn) && codes(settings).some(c => c.on);
}

/* ПРОЦЕНТ, КОТОРЫЙ ВИДИТ ПОКУПАТЕЛЬ, — и единственное место, где витрина
 * спрашивает скидку товара.
 *
 * Скидка витрины И ЕСТЬ скидка промокода по умолчанию (см. шапку файла),
 * поэтому выключенная промоакция снимает её целиком: покупатель платит полную
 * цену товара, а вместе со скидкой уходят плашка на снимке, зачёркнутая цена и
 * процент выгоды. Обещать «−20%» от имени кода, которого больше нет, — то же
 * самое, что обещать акцию на распроданном товаре.
 *
 * ЦЕНА В КАТАЛОГЕ при этом не меняется: `price` — цена БЕЗ скидки, она же и
 * платится. Выключение не поднимает цены задним числом — оно перестаёт их
 * опускать.
 *
 * Спрашивают её ВСЕ одним способом — карточка каталога, страница товара и общий
 * разбор позиции (`lib/pricing.js`): своего `D.discountPct` в этих местах быть
 * не должно, иначе выключенная акция пропала бы из карточки, но осталась в
 * корзине. Панель — другое дело: там владелец правит скидку самого товара и
 * обязан видеть её всегда. Закреплено тестом.
 */
function pctFor(product, settings) {
  const state = stateOf(settings, null);
  // Кода по умолчанию нет — скидки на витрине нет тоже: её даёт код, а не товар.
  return state.system && state.promo ? D.discountPct(product) : 0;
}

/* Цена сборки ГЛАЗАМИ ВИТРИНЫ: карточка каталога и страница товара показывают
 * её для кода, применённого по умолчанию, — того самого, который покупатель
 * получает, ничего не вводя. Одна дверь на оба места: посчитанная порознь, цена
 * карточки разошлась бы с ценой корзины на первом же округлении.
 */
function shopPrice(sum, product, settings) {
  return priceFor(sum, pctFor(product, settings), stateOf(settings, null));
}

// Включённый код по его набранному виду.
function byCode(settings, code) {
  if (!enabled(settings)) return null;
  const want = normCode(code);
  if (!want) return null;
  return codes(settings).find(c => c.on && c.code === want) || null;
}

/* Код, применённый по умолчанию, — тот, чья скидка уже стоит в ценнике витрины.
 * Только «скидка товара» (см. шапку файла): выбранный по ошибке код со своим
 * процентом не применяется молча ко всему каталогу, а просто не применяется. */
function defaultCode(settings) {
  const entry = byCode(settings, settings && settings.promoDefault);
  return entry && entry.percent === 0 ? entry : null;
}

/* Что применено к корзине ЭТОГО покупателя.
 *
 * `choice` приходит от витрины: `{code}` — введённый код, `{off: true}` — код
 * снят руками. Ни того ни другого (старая вкладка, первый заход) — применён код
 * по умолчанию: покупатель видел цены со скидкой и обязан получить их же.
 *
 * Неизвестный код возвращает к коду по умолчанию, а не снимает скидку: код мог
 * быть удалён в панели, пока корзина лежала, и молча поднимать из-за этого цены
 * нельзя.
 */
function stateOf(settings, choice) {
  if (!enabled(settings)) return { system: false, promo: null, off: false };
  const c = choice && typeof choice === 'object' ? choice : {};
  if (c.code) {
    const found = byCode(settings, c.code);
    if (found) return { system: true, promo: found, off: false };
    return { system: true, promo: defaultCode(settings), off: false };
  }
  if (c.off) return { system: true, promo: null, off: true };
  return { system: true, promo: defaultCode(settings), off: false };
}

/* Полную цену платит только тот, кто СНЯЛ код руками.
 *
 * Разница не косметическая: кода по умолчанию может не быть вовсе (владелец
 * выбрал «не применять» или выключил его в списке), и «нет применённого кода»
 * тогда означает обычную витрину со скидками товаров, а не поднятые для всех
 * цены. Без этой проверки один непрожатый селект в панели молча удваивал бы
 * ценник в корзине у каждого покупателя.
 */
function removed(state) { return !!(state && state.system && state.off); }

/* Цена сборки и цена для сравнения при этом коде — ЕДИНСТВЕННОЕ место, где
 * промокод превращается в деньги.
 *
 *   sum — ПОЛНАЯ цена сборки, как её считает витрина: `PF.priceOf()` плюс
 *         доплаты. Скидки в ней нет: она вся живёт здесь;
 *   pct — скидка товара (`PROMO.pctFor`), которую даёт код по умолчанию;
 *   state — результат `stateOf()`.
 *
 * Возвращает `{price, compare, full}`: `price` — сколько платить, `compare` —
 * что зачеркнуть (ноль — зачёркивать нечего), `full` — цена без скидки.
 *
 * ГЛАВНОЕ ПРАВИЛО: скидку даёт КОД. Нет применённого кода — нет и скидки, а
 * значит покупатель платит полную цену: и когда промоакция выключена вовсе, и
 * когда код снят руками, и когда владелец выбрал «не применять по умолчанию».
 * Прежде цена ценника уже содержала скидку, и выключенная акция ничего не
 * меняла — то есть акция, которой нет, продолжала действовать.
 */
function priceFor(sum, pct, state) {
  const full = Math.max(0, Number(sum) || 0);
  // Кода нет — платим полную цену. Зачёркивать при этом нечего: сравнивать её
  // не с чем, а зачёркнутая цена рядом с той же суммой читалась бы как обман.
  if (!state || !state.system || state.off || !state.promo) return { price: full, compare: 0, full };
  /* Код по умолчанию («скидка товара») даёт процент самого товара, код со своим
   * процентом — свой. Из двух берём тот, что выгоднее покупателю: применивший
   * законный код и увидевший цену ВЫШЕ ценника читает это как обман. */
  const own = D.saleFor(full, pct);
  const price = state.promo.percent ? Math.min(own, D.saleFor(full, state.promo.percent)) : own;
  return { price, compare: price < full ? full : 0, full };
}

/* Что показать покупателю на оформлении. Ту же строку отдают `/api/cart` и
 * `/api/promo`, поэтому витрине не приходится держать свою копию правил: она
 * рисует то, что ответил сервер.
 */
function view(settings, choice) {
  const state = stateOf(settings, choice);
  return {
    on: state.system,
    code: state.promo ? state.promo.code : '',
    percent: state.promo ? state.promo.percent : 0,
    off: state.off,
    // Есть ли к чему возвращаться кнопкой «Вернуть»: код по умолчанию мог быть
    // выключен в панели, пока покупатель ходил по витрине.
    fallback: state.system && defaultCode(settings) ? defaultCode(settings).code : ''
  };
}

/* Выбор покупателя из тела запроса. Одна разборка на все маршруты: `/api/cart`,
 * `/api/promo` и `/api/order` обязаны понимать витрину одинаково.
 *
 * Отсутствие полей — это «как по умолчанию», а не «снят»: старые вкладки, у
 * которых этих полей нет вовсе, должны продолжать видеть цены со скидкой.
 */
function choiceFrom(body) {
  const b = body && typeof body === 'object' ? body : {};
  const code = normCode(b.promoCode);
  if (code) return { code };
  if (b.promoOff === true || b.promoOff === 'true' || b.promoOff === 1 || b.promoOff === '1') return { off: true };
  return null;
}

module.exports = {
  MAX_CODES, CODE_MAX, CODE_RE, MAX_PCT: D.MAX_PCT,
  normCode, validCode, cleanPercent, cleanEntry, codes,
  enabled, pctFor, shopPrice, byCode, defaultCode, stateOf, removed, priceFor, view, choiceFrom
};
