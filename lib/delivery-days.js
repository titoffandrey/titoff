'use strict';
/* ========================= Срок доставки: своя сетка =========================
 * «Сколько ждать» — второй вопрос покупателя после «сколько стоит», и на
 * оформлении он обязан стоять рядом с ценой: пункт выдачи в соседнем городе
 * дешевле курьера, но приедет позже, и выбирать вслепую между ними нельзя.
 *
 * Считаем сами, как и цену (lib/delivery-price.js): калькуляторы перевозчиков
 * требуют договора, ключей и живой сети на каждом открытии оформления, а
 * внешних зависимостей у проекта нет. Сетка та же по устройству —
 * [способ][вариант][зона], — поэтому цена и срок правятся рядом и одинаково.
 *
 * Что за посылка: та же «средняя» — около 2 кг, отправка ВСЕГДА из Москвы,
 * обычная наземная доставка, БЕЗ экспресс-тарифов. Экспресс у обоих
 * перевозчиков стоит вдвое-втрое дороже нашей сетки, и обещать его сроки по
 * цене обычной посылки нельзя.
 *
 * Откуда числа — публичные сроки обоих перевозчиков из Москвы, усреднённые по
 * зоне (внутри одной зоны города разбросаны: Петербург ближе Мурманска,
 * Екатеринбург ближе Салехарда — берём вилку, накрывающую оба):
 *   - СДЭК до ПВЗ: Петербург 1–2, Екатеринбург 2–3, Новосибирск 3–4,
 *     Краснодар 2–4, Владивосток 6–8.
 *   - OZON: своя логистика идёт дольше СДЭК на дальних зонах — Екатеринбург
 *     4–5, Новосибирск 5–6, Владивосток 8–12.
 *   - Курьером до двери — на день дольше пункта выдачи: посылка сперва
 *     доезжает до того же склада, а потом ещё день ждёт своего маршрута.
 *
 * ДНИ КАЛЕНДАРНЫЕ И С ЗАПАСОМ. Перевозчики считают в рабочих, но покупатель
 * читает «3 дня» как три дня от сегодня, и пятничный заказ по рабочему счёту
 * приехал бы позже обещанного. Опоздать хуже, чем приехать раньше.
 *
 * Срок — такое же коммерческое обещание, как тариф: числа правятся здесь, в
 * одном месте. Сетка обязана быть полной (все зоны у каждого способа и
 * варианта), а курьер не может опережать пункт выдачи — закреплено тестом.
 */

const DELIVERY = require('./delivery');
const Z = require('./delivery-zones');

// [способ][вариант][зона] — [от, до] дней от отправки из Москвы.
const DAYS = {
  cdek: {
    pvz: {
      msk: [1, 2], cfo: [2, 3], szfo: [2, 4], pfo: [3, 4], yug: [3, 5],
      ural: [3, 5], sfo: [4, 6], dfo: [6, 9], ru: [3, 6]
    },
    courier: {
      msk: [1, 2], cfo: [2, 4], szfo: [3, 4], pfo: [3, 5], yug: [4, 6],
      ural: [4, 6], sfo: [5, 7], dfo: [7, 10], ru: [4, 7]
    }
  },
  ozon: {
    pvz: {
      msk: [1, 2], cfo: [2, 4], szfo: [3, 4], pfo: [3, 5], yug: [4, 6],
      ural: [4, 6], sfo: [5, 7], dfo: [7, 11], ru: [4, 7]
    },
    courier: {
      msk: [2, 3], cfo: [3, 5], szfo: [4, 5], pfo: [4, 6], yug: [5, 7],
      ural: [5, 7], sfo: [6, 8], dfo: [8, 12], ru: [5, 8]
    }
  }
};

/* Вилка срока по сетке. Неизвестный способ, вариант или зона — `null`: срок
 * выдумывать нельзя ровно так же, как цену, а вызывающий по пустому значению
 * просто ничего не покажет.
 */
function daysFor(method, mode, zoneId) {
  const byMode = DAYS[String(method == null ? '' : method)];
  const byZone = byMode && byMode[String(mode == null ? '' : mode)];
  const range = byZone && byZone[String(zoneId == null ? '' : zoneId)];
  if (!Array.isArray(range) || range.length !== 2) return null;
  const min = Number(range[0]), max = Number(range[1]);
  if (!Number.isFinite(min) || !Number.isFinite(max) || min <= 0 || max < min) return null;
  return { min, max };
}

// «день / дня / дней». Своя, а не из lib/render.js: рендер сюда тянуть незачем,
// а слово здесь ровно одно.
function dayWord(n) {
  const t = Math.abs(n) % 100, u = t % 10;
  if (t > 10 && t < 20) return 'дней';
  if (u === 1) return 'день';
  if (u >= 2 && u <= 4) return 'дня';
  return 'дней';
}

/* Срок словами: «2–3 дня», «7–11 дней». Склоняем по верхней границе — так
 * читается диапазон вслух.
 *
 * Текст собирает СЕРВЕР и отдаёт витрине готовым — как и список способов
 * доставки: своя вилка со своим склонением в скрипте разошлась бы с серверной
 * молча, а покупатель увидел бы один срок на карточке и другой в сводке.
 */
function text(range) {
  if (!range) return '';
  const { min, max } = range;
  const num = min === max ? String(max) : min + '–' + max;
  return num + ' ' + dayWord(max);
}

function textFor(method, mode, zoneId) { return text(daysFor(method, mode, zoneId)); }

/* Сроки сразу всех способов и вариантов по зоне — тем же срезом, что и цены в
 * `SHIP.quoteAll`: покупатель должен видеть срок курьера ДО того, как выберет
 * его, а переключение способа не должно ходить на сервер.
 */
function textAll(zoneId) {
  const out = {};
  for (const m of DELIVERY.METHODS) {
    out[m.id] = {};
    for (const mode of m.modes) out[m.id][mode.id] = textFor(m.id, mode.id, zoneId);
  }
  return out;
}

/* Сроки по всей стране одной строкой — для консультанта в чате.
 *
 * «Когда придёт» спрашивают в чате не реже, чем «сколько стоит», и отвечать на
 * это «уточнит менеджер», когда срок уже написан на оформлении рядом, нельзя:
 * покупатель видит два разных ответа на одной странице. Берётся та же сетка,
 * что и на витрине, — своих чисел в тексте промпта быть не должно.
 *
 * Вилка по зоне — от самого быстрого перевозчика до самого медленного: в чате
 * речь про доставку вообще, а перевозчика покупатель выберет на оформлении.
 * Зона «регион не опознан» пропускается: это наша тарифная страховка, а не
 * место на карте.
 */
function summary() {
  const parts = [];
  for (const z of Z.ZONES) {
    if (z.id === Z.FALLBACK) continue;
    let min = Infinity, max = 0;
    for (const m of DELIVERY.METHODS) {
      const range = daysFor(m.id, 'pvz', z.id);
      if (!range) continue;
      min = Math.min(min, range.min);
      max = Math.max(max, range.max);
    }
    if (!max) continue;
    parts.push(z.name + ' — ' + text({ min, max }));
  }
  return parts.join(', ');
}

module.exports = { DAYS, daysFor, dayWord, text, textFor, textAll, summary };
