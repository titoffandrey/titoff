'use strict';
/* ========================= Срок доставки: своя сетка =========================
 * «Сколько ждать» — второй вопрос покупателя после «сколько стоит», и на
 * оформлении он обязан стоять рядом с ценой: пункт выдачи в соседнем городе
 * дешевле курьера, но приедет позже, и выбирать вслепую между ними нельзя.
 *
 * Считаем сами, как и цену (lib/delivery-price.js): калькуляторы перевозчиков
 * требуют договора, ключей и живой сети на каждом открытии оформления, а
 * внешних зависимостей у проекта нет.
 *
 * СРОК СЧИТАЕТСЯ ОТ ОФОРМЛЕНИЯ, а не от передачи посылки перевозчику. Это и
 * есть тот вопрос, который задаёт покупатель: «3 дня» он читает как «в среду»,
 * а не как «через три дня после того, как вы её куда-то отвезёте». Поэтому
 * срок складывается из трёх частей, и каждая живёт отдельно — их правят по
 * разным поводам:
 *
 *   1. ОТСЕЧКА. Заказ после 16:00 по Москве (и любой заказ в выходной) уходит в
 *      работу следующим рабочим днём. Без этого пятничный вечерний заказ
 *      обещал бы понедельничный срок, а поехал бы во вторник.
 *   2. СБОРКА — рабочие дни от приёма заказа в работу до передачи перевозчику:
 *      подтвердить предоплаченный заказ, собрать и отвезти в пункт приёма.
 *   3. ТРАНЗИТ — календарные дни у самого перевозчика. Линейные перевозки идут
 *      и в выходные, поэтому здесь считаются календарные дни, а не рабочие;
 *      воскресное прибытие переносится на понедельник — курьер в воскресенье не
 *      ездит, а часть пунктов выдачи закрыта.
 *
 * ЧЕМ ЭТО БЫЛО РАНЬШЕ. Сетка называлась «дней от отправки из Москвы», а на
 * витрине те же числа стояли ответом на «когда приедет». Сборки не было вовсе,
 * дня недели никто не спрашивал — то есть обещание было заведомо короче правды
 * на сутки-двое у каждого заказа и на четверо у пятничного вечернего. Разница
 * не косметическая: срок покупатель запоминает и по нему судит, обманули его
 * или нет.
 *
 * ДНИ КАЛЕНДАРНЫЕ И С ЗАПАСОМ — теперь это не пожелание в комментарии, а
 * арифметика: рабочие дни сборки раскладываются по календарю честно.
 * Опоздать хуже, чем приехать раньше.
 *
 * Откуда числа транзита — публичные сроки обоих перевозчиков из Москвы,
 * усреднённые по зоне (внутри одной зоны города разбросаны: Петербург ближе
 * Мурманска, Екатеринбург ближе Салехарда — берём вилку, накрывающую оба):
 *   - СДЭК наземными тарифами до ПВЗ: Петербург 1–2 рабочих дня, Екатеринбург
 *     2–3, Новосибирск 3–5, Владивосток 5–8. В календарных это примерно
 *     +1–3 дня на выходные в пути.
 *   - OZON: своя логистика идёт дольше СДЭК на дальних зонах.
 *   - Курьером до двери — на день дольше пункта выдачи: посылка сперва
 *     доезжает до того же склада, а потом ещё день ждёт своего маршрута.
 *   - Верхняя граница взята с запасом на пересортировку: она случается не как
 *     исключение, а как обычное дело, и промолчать о ней значит промахнуться
 *     ровно в том случае, ради которого срок и спрашивают.
 *
 * Считаем обычную наземную доставку, БЕЗ экспресс-тарифов: экспресс у обоих
 * перевозчиков стоит вдвое-втрое дороже нашей сетки, и обещать его сроки по
 * цене обычной посылки нельзя.
 *
 * Срок — такое же коммерческое обещание, как тариф: числа правятся здесь, в
 * одном месте. Сетка обязана быть полной (все зоны у каждого способа и
 * варианта), а курьер не может опережать пункт выдачи — закреплено тестом.
 */

const DELIVERY = require('./delivery');
const Z = require('./delivery-zones');

// [способ][вариант][зона] — [от, до] календарных дней у перевозчика: от
// передачи ему посылки до вручения.
const TRANSIT = {
  cdek: {
    pvz: {
      msk: [1, 2], cfo: [2, 3], szfo: [2, 4], pfo: [3, 4], yug: [3, 5],
      ural: [3, 5], sfo: [4, 6], dfo: [7, 10], ru: [3, 6]
    },
    courier: {
      msk: [2, 3], cfo: [3, 4], szfo: [3, 5], pfo: [4, 5], yug: [4, 6],
      ural: [4, 6], sfo: [5, 7], dfo: [8, 11], ru: [4, 7]
    }
  },
  ozon: {
    pvz: {
      msk: [1, 3], cfo: [2, 4], szfo: [3, 5], pfo: [3, 5], yug: [4, 6],
      ural: [4, 6], sfo: [5, 7], dfo: [8, 11], ru: [4, 7]
    },
    courier: {
      msk: [2, 4], cfo: [3, 5], szfo: [4, 6], pfo: [4, 6], yug: [5, 7],
      ural: [5, 7], sfo: [6, 8], dfo: [9, 12], ru: [5, 8]
    }
  }
};

/* Сборка заказа — РАБОЧИЕ дни от приёма заказа в работу до передачи
 * перевозчику: подтвердить предоплаченный заказ, собрать и отвезти в пункт
 * приёма.
 *
 * Ровно один день, а не вилка «1–2», и это осознанно. Запас в сроке нужен там,
 * где мы ни на что не влияем, — у перевозчика; наша собственная работа
 * запасом не оправдывается. Заложи мы вторые сутки на себя, и вилка выросла бы
 * на день у КАЖДОГО заказа (замер: Москва «2–3 дня» превращалась в «2–4», Урал
 * «4–6» в «4–9») — то есть магазин обещал бы хуже, чем умеет, на всех
 * направлениях сразу. Не успели в свой день — это разговор менеджера с
 * покупателем, а не строка на витрине.
 *
 * Это не то же самое, что отсечка ниже: та решает, с какого ДНЯ начинается
 * отсчёт, а здесь — сколько дней занимает сама работа.
 */
const HANDLING = 1;

/* После этого часа по Москве заказ уходит в работу следующим рабочим днём: в
 * пункт приёма перевозчика вечером уже не успеть.
 */
const CUTOFF_HOUR = 16;

/* Календарь считаем ПО МОСКВЕ, а не по часам процесса: сервер живёт в UTC, и
 * заказ, оформленный в 23:30 по Москве, по его часам приходится на предыдущий
 * день — то есть попал бы в другой день недели (см. «Время магазина —
 * московское» в CLAUDE.md). Смещение здесь своё, постоянное: тянуть сюда
 * `lib/render.js` нельзя — он сам подключает этот модуль через
 * `lib/tracking.js`, и require замкнулся бы в кольцо. У Москвы смещение
 * неизменно с 2014 года; то же решение и по той же причине стоит в
 * `lib/tracking.js`.
 */
const DAY_MS = 24 * 60 * 60 * 1000;
const MSK_OFFSET_MS = 3 * 60 * 60 * 1000;

// Номер дня по Москве (сплошной счёт от 1 января 1970) и час внутри него.
function mskDay(ms) { return Math.floor((ms + MSK_OFFSET_MS) / DAY_MS); }
function mskHour(ms) { return Math.floor(((ms + MSK_OFFSET_MS) % DAY_MS) / 3600000); }

// День недели номера дня: 0 — воскресенье, 6 — суббота. 1 января 1970 было
// четвергом, отсюда сдвиг на 4.
function weekday(day) { return (((day + 4) % 7) + 7) % 7; }
function isWorkday(day) { const w = weekday(day); return w >= 1 && w <= 5; }
function nextWorkday(day) { let d = day; while (!isWorkday(d)) d++; return d; }

// Прибавить рабочие дни: каждый шаг — следующий рабочий день после текущего.
function addWorkdays(day, n) {
  let d = day;
  for (let i = 0; i < n; i++) d = nextWorkday(d + 1);
  return d;
}

/* День приёма заказа в работу. Заказ после отсечки и заказ в выходной ждут
 * ближайшего рабочего дня: это факт, а не вилка, поэтому у нижней и верхней
 * границы срока он общий.
 */
function intakeDay(at) {
  const day = mskDay(at);
  return nextWorkday(mskHour(at) >= CUTOFF_HOUR ? day + 1 : day);
}

/* День вручения: транзит считается календарными днями от дня передачи посылки
 * перевозчику — линейные перевозки идут и в выходные. В воскресенье не возят и
 * не всегда выдают, поэтому воскресное прибытие переносим на понедельник — как
 * и всё остальное в этом модуле, в сторону «позже».
 */
function arrivalDay(shipped, transit) {
  const at = shipped + transit;
  return weekday(at) === 0 ? at + 1 : at;
}

/* Транзитная вилка перевозчика — календарные дни ОТ ПЕРЕДАЧИ ему посылки.
 * Нужна отслеживанию (`lib/tracking.js`): маршрут посылки начинается там, где
 * перевозчик её принял, и сборка магазина в него не входит.
 *
 * Неизвестный способ, вариант или зона — `null`: срок выдумывать нельзя ровно
 * так же, как цену, а вызывающий по пустому значению просто ничего не покажет.
 */
function transitFor(method, mode, zoneId) {
  const byMode = TRANSIT[String(method == null ? '' : method)];
  const byZone = byMode && byMode[String(mode == null ? '' : mode)];
  const range = byZone && byZone[String(zoneId == null ? '' : zoneId)];
  if (!Array.isArray(range) || range.length !== 2) return null;
  const min = Number(range[0]), max = Number(range[1]);
  if (!Number.isFinite(min) || !Number.isFinite(max) || min <= 0 || max < min) return null;
  return { min, max };
}

/* Вилка срока для покупателя — календарные дни ОТ ОФОРМЛЕНИЯ.
 *
 * `now` — момент заказа; по умолчанию «сейчас». Он здесь не для тестов: от дня
 * недели и часа зависит и день приёма в работу, и то, сколько выходных попадёт
 * в срок. Один и тот же адрес честно даёт разный ответ в понедельник утром и в
 * пятницу вечером — так же считают и сами перевозчики.
 */
function daysFor(method, mode, zoneId, now) {
  const transit = transitFor(method, mode, zoneId);
  if (!transit) return null;
  const at = Number(now) > 0 ? Number(now) : Date.now();
  const ordered = mskDay(at);
  const shipped = addWorkdays(intakeDay(at), HANDLING);
  const min = arrivalDay(shipped, transit.min) - ordered;
  const max = arrivalDay(shipped, transit.max) - ordered;
  return { min: Math.max(1, min), max: Math.max(min, max) };
}

// «день / дня / дней». Своя, а не из lib/render.js: рендер сюда тянуть незачем,
// а слово здесь ровно одно.
function dayWord(n) {
  const t = Math.abs(n) % 100, u = t % 10;
  if (t > 10 && t < 20) return 'дней';
  if (u === 1) return 'день';
  if (u >= 2 && u <= 4) return 'дня';
  return 'дней';
}

/* Срок словами: «2–3 дня», «7–11 дней». Склоняем по верхней границе — так
 * читается диапазон вслух.
 *
 * Текст собирает СЕРВЕР и отдаёт витрине готовым — как и список способов
 * доставки: своя вилка со своим склонением в скрипте разошлась бы с серверной
 * молча, а покупатель увидел бы один срок на карточке и другой в сводке.
 */
function text(range) {
  if (!range) return '';
  const { min, max } = range;
  const num = min === max ? String(max) : min + '–' + max;
  return num + ' ' + dayWord(max);
}

function textFor(method, mode, zoneId, now) { return text(daysFor(method, mode, zoneId, now)); }

/* Сроки сразу всех способов и вариантов по зоне — тем же срезом, что и цены в
 * `SHIP.quoteAll`: покупатель должен видеть срок курьера ДО того, как выберет
 * его, а переключение способа не должно ходить на сервер.
 */
function textAll(zoneId, now) {
  const at = Number(now) > 0 ? Number(now) : Date.now();
  const out = {};
  for (const m of DELIVERY.METHODS) {
    out[m.id] = {};
    for (const mode of m.modes) out[m.id][mode.id] = textFor(m.id, mode.id, zoneId, at);
  }
  return out;
}

/* Сроки по всей стране одной строкой — для консультанта в чате.
 *
 * «Когда придёт» спрашивают в чате не реже, чем «сколько стоит», и отвечать на
 * это «уточнит менеджер», когда срок уже написан на оформлении рядом, нельзя:
 * покупатель видит два разных ответа на одной странице. Берётся та же сетка,
 * что и на витрине, — своих чисел в тексте промпта быть не должно.
 *
 * Здесь это ТРАНЗИТ, а не полный срок от заказа, и не по недосмотру: строка
 * уезжает в постоянную часть промпта, которую кэширует OpenAI, а полный срок
 * зависит от дня недели и часа — такая строка обнуляла бы кэш всему магазину
 * дважды в сутки (см. «Токены» в CLAUDE.md). Сборку консультант называет
 * отдельной фразой (`handlingText`), а точный срок от сегодняшнего дня
 * показывает оформление.
 *
 * Вилка по зоне — от самого быстрого перевозчика до самого медленного: в чате
 * речь про доставку вообще, а перевозчика покупатель выберет на оформлении.
 * Зона «регион не опознан» пропускается: это наша тарифная страховка, а не
 * место на карте.
 */
function summary() {
  const parts = [];
  for (const z of Z.ZONES) {
    if (z.id === Z.FALLBACK) continue;
    let min = Infinity, max = 0;
    for (const m of DELIVERY.METHODS) {
      const range = transitFor(m.id, 'pvz', z.id);
      if (!range) continue;
      min = Math.min(min, range.min);
      max = Math.max(max, range.max);
    }
    if (!max) continue;
    parts.push(z.name + ' — ' + text({ min, max }));
  }
  return parts.join(', ');
}

/* Сборка словами — вторая половина ответа консультанта. Тоже постоянная
 * строка: числа берутся из тех же констант, что и расчёт, но от «сегодня» не
 * зависят.
 */
function handlingText() {
  return 'Заказ собираем и передаём перевозчику на следующий рабочий день после оплаты'
    + ' (' + HANDLING + ' ' + dayWord(HANDLING) + '); оплаченные после ' + CUTOFF_HOUR
    + ':00 по Москве и в выходные уезжают следующим рабочим днём.'
    + ' Поэтому срок от дня заказа выходит длиннее транзита, и точное число дней'
    + ' показывает оформление после ввода адреса.';
}

module.exports = {
  TRANSIT, HANDLING, CUTOFF_HOUR,
  transitFor, daysFor, dayWord, text, textFor, textAll, summary, handlingText,
  // Наружу нужны и календарные мелочи: по ним тест проверяет, что срок правда
  // раскладывается по дням недели, а не прибавляет фиксированную поправку.
  intakeDay, arrivalDay, weekday, isWorkday
};
