/* Кэш строки каталога. Ключ — ССЫЛКА на массив товаров: `db.readJson` отдаёт
 * один и тот же объект, пока не изменился mtime файла, поэтому WeakMap
 * протухает вместе с перечитанным каталогом сам. Тот же приём, что у
 * `reviewIndex()` в `lib/db.js` и у строки поиска в `lib/search.js`.
 *
 * Без него список собирался бы заново на каждое сообщение каждого покупателя —
 * с обходом всех вариантов каждого товара ради цены. */
const catalogCache = new WeakMap();

/* Каталог идёт ТАБЛИЦЕЙ, а не фразами, и подписи столбцов стоят один раз в
 * шапке. Списком «категория: iPhone · варианты: … · цвета: …» те же сведения
 * занимали на треть больше: подписи повторялись у каждого из 44 товаров, а
 * платим мы за них в каждом сообщении каждого покупателя (замер: 7 572 знака
 * против 5 100). Модель читает столбцы не хуже фраз — лишь бы шапка честно
 * называла, что в них лежит. */
const CATALOG_HEAD = 'ТОВАРЫ МАГАЗИНА. Строка = товар, поля через «|»: '
  + 'название | раздел | цена (от — за самую доступную сборку, доплаты за память и цвет считаются в карточке) | '
  + 'наличие (есть / мало = осталось несколько штук / нет) | память или размер | цвета | '
  + 'id карточки, её адрес — /product/id';

function catalogText(db, settings) {
  const products = db.visibleProducts();
  const hit = catalogCache.get(products);
  if (hit && hit.currency === (settings.currency || '')) return hit.text;

  const lines = [];
  for (const p of products.slice(0, MAX_PRODUCTS)) {
    // `sellable` знает и про распроданные варианты, и про потолок кассы: товар
    // дороже него на витрине висит как «Нет в наличии», и обещать его нельзя.
    const canBuy = R.sellable(p, settings);
    const from = R.startPrice(p);
    const pct = Number(p.discountPercent) || 0;
    const parts = [p.name, p.category || 'Прочее'];
    parts.push((p.storages && p.storages.length ? 'от ' : '') + R.money(from, settings) + (pct ? ` -${pct}%` : ''));
    parts.push(canBuy ? (p.stockLevel === 'few' ? 'мало' : 'есть') : 'нет');
    // Варианты называем перечнем, а не описанием: покупатель спрашивает «есть
    // 512 ГБ в чёрном?», и ответ должен браться из данных, а не из общих слов.
    // У распроданного товара их не перечисляем вовсе: выбирать всё равно не из
    // чего, а место в каждом запросе они занимают.
    const storages = canBuy ? (p.storages || []).filter(s => s && s.inStock !== false).map(s => s.label).filter(Boolean) : [];
    const colors = canBuy ? (p.colors || []).filter(c => c && c.inStock !== false).map(c => c.name).filter(Boolean) : [];
    parts.push(storages.join(', '), colors.join(', '), p.id);
    lines.push(parts.join('|'));
  }
  const text = lines.length ? CATALOG_HEAD + '\n' + lines.join('\n') : 'Каталог сейчас пуст.';
  catalogCache.set(products, { text, currency: settings.currency || '' });
  return text;
}

/* Условия магазина, которые спрашивают чаще всего. Всё берётся из тех же
 * модулей, что рисуют витрину: перевозчики — из `lib/delivery.js`, оплата — из
 * router'а касс. Перечисленные словами, они разошлись бы с оформлением ровно
 * так же, как переписанный руками каталог. */
function storeText(settings) {
  const lines = [];
  lines.push('Магазин: ' + (settings.storeName || 'магазин') + (settings.tagline ? ' — ' + settings.tagline : '') + '.');
  const carriers = DELIVERY.METHODS.map(m => m.name);
  if (carriers.length) {
    lines.push('Доставка по России: ' + carriers.join(' и ') + ', в пункт выдачи или курьером до двери. '
      + 'Стоимость считается по адресу на оформлении и показывается там же до оплаты. Отправка из Москвы.');
    // Срок берётся из той же сетки, что показывает оформление (lib/delivery-days.js):
    // «уточнит менеджер» рядом с написанным на странице «3–5 дней» — это два
    // разных ответа на один вопрос в пределах одного экрана.
    lines.push('Сроки доставки из Москвы в пункт выдачи (обычная доставка, не экспресс): '
      + SHIPDAYS.summary() + '. Курьером до двери — на день-два дольше. '
      + 'Точный срок и цену показывает оформление после ввода адреса.');
  }
  if (PAYMENTS.enabled(settings)) {
    const limits = PAYMENTS.limits(settings);
    lines.push('Оплата на сайте: перевод по реквизитам (СБП или на карту), предоплата. '
      + 'Данные карты магазин не спрашивает и не получает.'
      + (limits.max ? ` Один заказ — от ${R.money(limits.min, settings)} до ${R.money(limits.max, settings)}.` : ''));
  } else {
    lines.push('Оплата: после оформления заявки менеджер связывается и подтверждает заказ.');
  }
  lines.push('Гарантия 1 год на технику, 1 месяц на аксессуары, подробности на странице /warranty.');
  lines.push('Возврат: 7 дней на отказ при дистанционной покупке, подробности на /returns.');
  if (settings.contactTelegram) lines.push('Telegram магазина: ' + settings.contactTelegram + '.');
  return 'ОБ УСЛОВИЯХ:\n' + lines.map(l => '- ' + l).join('\n');
}

/* Где стоит покупатель прямо сейчас. Это то, ради чего ИИ вообще полезен на
 * витрине: вопрос «а 512 есть?» задают, глядя на карточку, и переспрашивать
 * «какая модель?» у человека, который смотрит на неё, — худший способ начать
 * разговор. */
function placeText(db, settings, info) {
  const lines = [];
  const page = String(info && info.page || '');
  const match = /^\/product\/([a-z0-9-]+)$/.exec(page);
  if (match) {
    const p = db.visibleProduct(match[1]);
    if (p) {
      lines.push('Покупатель сейчас смотрит карточку: ' + p.name
        + ' — ' + R.money(R.startPrice(p), settings) + (R.sellable(p, settings) ? '' : ', нет в наличии') + '.');
    }
  } else if (page === '/checkout') lines.push('Покупатель сейчас на странице оформления заказа.');
  else if (page && page !== '/') lines.push('Покупатель сейчас на странице ' + page + '.');

  // Корзина приезжает от витрины — она и живёт в браузере. Проверять её состав
  // по каталогу здесь не нужно: цену всё равно считает `/api/order` заново.
  const cart = Array.isArray(info && info.cart) ? info.cart.slice(0, 20) : [];
  if (cart.length) {
    const items = cart.map(it => String(it && it.name || '').slice(0, 120) + (Number(it && it.qty) > 1 ? ' × ' + Math.floor(Number(it.qty)) : ''))
      .filter(Boolean);
    if (items.length) lines.push('В корзине у него: ' + items.join('; ') + '.');
  }

  /* Его заказы и что с их оплатой.
   *
   * «Где мой заказ» и «оплатил, а статус прежний» — самые частые вопросы в
   * чате, и без этих строк консультант отвечает единственным доступным ему
   * способом: переспрашивает номер заказа у человека, который сидит на странице
   * оплаты. Заказы подбирает сервер по метке посетителя — той же, что стоит в
   * самой заявке; чужие сюда попасть не могут.
   *
   * Реквизитов, адреса и телефона здесь нет намеренно: они не нужны ни для
   * одного ответа, а в модель уходит ровно то, без чего не обойтись.
   */
  const orders = Array.isArray(info && info.orders) ? info.orders.slice(0, 5) : [];
  if (orders.length) {
    lines.push('Его заказы (говори о них только по этим данным, ничего не додумывай):');
    for (const o of orders) {
      const view = R.payView(o) || { label: 'оплата не запускалась' };
      const items = (Array.isArray(o.items) ? o.items : []).map(i => String(i && i.name || '')).filter(Boolean);
      lines.push('  ' + R.orderNo(o.number) + ' от ' + R.formatDate(o.createdAt)
        + ' — ' + R.money(o.total, settings) + ', оплата: ' + view.label
        + (items.length ? '; в заказе: ' + items.join('; ').slice(0, 200) : ''));
    }
  }
  return lines.length ? 'ГДЕ ПОКУПАТЕЛЬ:\n' + lines.map(l => '- ' + l).join('\n') : '';
}

// Инструкция владельца. Стоит ПОСЛЕ правил и фактов: то, что ближе к концу,
// модель держит охотнее, а это и есть голос конкретного магазина — его тон,
// его сценарий разговора, его исключения.
function instructionText(settings) {
  const raw = String(settings && settings.chatPrompt || '').trim().slice(0, MAX_INSTRUCTION);
  return raw ? 'ИНСТРУКЦИЯ ВЛАДЕЛЬЦА МАГАЗИНА (следуй ей в тоне и в том, что говорить):\n' + raw : '';
}

/* НЕИЗМЕННАЯ ЧАСТЬ ЗАПРОСА, и она обязана быть именно неизменной.
 *
 * OpenAI кэширует запрос по САМОМУ ДЛИННОМУ СОВПАДАЮЩЕМУ НАЧАЛУ: то, что
 * совпало с прошлым запросом, считается по 0,1 обычной цены (замер на боевом
 * ключе: 3 840 токенов из 3 869 приезжают из кэша). Кэш живёт от последнего
 * обращения, поэтому в разговоре из пяти реплик за полную цену уезжает только
 * первая.
 *
 * Отсюда правило: всё постоянное — правила, условия, каталог, инструкция
 * владельца — стоит ЗДЕСЬ, в начале, и только оно. Изменчивое (страница,
 * корзина, заказы) уезжает отдельным сообщением в самый конец: попади оно в
 * середину, всё, что стоит ниже, перестало бы совпадать с прошлым запросом —
 * а ниже лежит инструкция владельца до 8000 знаков и вся переписка.
 */
function systemPrompt(db, settings) {
  return [
    RULES.map(r => '- ' + r).join('\n'),
    storeText(settings),
    catalogText(db, settings),
    instructionText(settings)
  ].filter(Boolean).join('\n\n');
}

/* Переписка в том виде, в каком её принимает модель. Реплики оператора идут
 * как assistant: для покупателя это один собеседник, и разрывать их на разные
 * роли значило бы, что ИИ, вернувшись в разговор, не увидит, о чём человек уже
 * договорился. Системные строки («оператор подключился») в модель не идут
 * вовсе — это подписи интерфейса, а не часть беседы. */
function historyFor(chat) {
  const out = [];
  for (const m of (chat && chat.messages || []).slice(-HISTORY)) {
    if (m.role === 'user') out.push({ role: 'user', content: m.text });
    else if (m.role === 'ai') out.push({ role: 'assistant', content: m.text });
    else if (m.role === 'operator') out.push({ role: 'assistant', content: m.text });
  }
  return out;
}

/* Порядок сообщений: постоянное → переписка → обстановка вокруг покупателя.
 *
 * Обстановка стоит ПОСЛЕ переписки, и это не вкусовщина. Переписка растёт
 * только с конца, поэтому «правила + каталог + все прошлые реплики» у каждого
 * следующего запроса совпадают с началом предыдущего — и приезжают из кэша
 * целиком. Стой изменчивый блок перед репликами (а он там и стоял, внутри
 * system-сообщения), совпадение обрывалось бы на нём, и вся переписка
 * оплачивалась бы заново на каждый вопрос.
 *
 * Заодно это и по делу: страница, корзина и заказы — то, что вернее всего
 * должно быть у модели перед глазами, когда она отвечает на последний вопрос.
 */
function build(db, settings, chat, info) {
  const messages = [{ role: 'system', content: systemPrompt(db, settings) }].concat(historyFor(chat));
  const place = placeText(db, settings, info);
  if (place) messages.push({ role: 'system', content: place });
  return messages;
}

module.exports = { RULES, HISTORY, MAX_INSTRUCTION, build, systemPrompt, catalogText, storeText, placeText, historyFor };
