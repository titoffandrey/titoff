    lines.push('Задержки в пути — обычное дело: перевозчик пересортировывает посылки, ждёт рейса, '
      + 'пункт выдачи бывает загружен. Посылка при этом не теряется, деньги не пропадают и заказ остаётся за покупателем — '
      + 'магазин ведёт его вместе с перевозчиком до самой выдачи. '
      + 'Спросили о задержке — сначала успокой: скажи, что так бывает, что переживать не нужно и что мы разберёмся, '
      + 'и только потом говори, что известно по заказу. Новую дату доставки не называй: её уточняет менеджер.');
