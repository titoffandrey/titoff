  'Задержка доставки — не повод пугать покупателя. Спрашивают, где посылка и почему так долго: сперва успокой — так бывает, посылка не теряется, заказ остаётся за ним и мы разберёмся, — и только потом скажи, что известно по заказу. Новую дату доставки не называй и не оправдывайся длинно: спокойной фразы и обещания разобраться достаточно.',
