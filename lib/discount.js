'use strict';
/* Скидка товара — ОДИН ПРОЦЕНТ на все конфигурации.
 *
 * Раньше скидка была суммой: у товара лежала старая цена, а зачёркнутая цена
 * варианта считалась как «старая цена базовой сборки + те же доплаты». Выгода в
 * рублях при этом сохранялась, а процент таял с каждой доплатой: iPhone 15 Pro
 * показывал −12% на базовой сборке и −8% на терабайтной. Для покупателя это
 * выглядело так, будто дорогая сборка ещё и менее выгодная, хотя скидка у
 * магазина одна на товар.
 *
 * Теперь наоборот: процент задаётся владельцем и постоянен, а зачёркнутая цена
 * из него ВЫВОДИТСЯ для каждой сборки — `цена / (1 − процент)`. Поэтому её и
 * нельзя править руками: это не отдельное число, а производная от цены и
 * процента, и любая правка тут же разошлась бы с одним из них.
 *
 * Считается это в одном месте на весь проект: карточка каталога, страница
 * товара, корзина, оформление и пересчёт варианта в браузере обязаны показывать
 * одну и ту же пару чисел.
 *
 * «Горящих скидок» (акция со своей ценой и таймером) больше нет вовсе — снята
 * вместе с полями `hotDeal`, `hotDealPrice`, `hotDealUntil`.
 */

// Больше 90% — уже не скидка, а опечатка: 95% превращают 68 000 ₽ в старую цену
// в 1 360 000 ₽. Верхняя граница одна на форму товара и на показ.
const MAX_PCT = 90;

/* Процент скидки товара.
 *
 * Источник истины — `discountPercent`. Старые данные (и живой каталог до
 * перехода) знают только пару «цена / старая цена», поэтому у товара без
 * процента он выводится из неё: витрина не должна терять скидку из-за того, что
 * товар ещё не пересохраняли. Первое же сохранение в панели запишет процент и
 * уберёт `oldPrice` (см. `updateProduct` в lib/db.js).
 */
function discountPct(p) {
  const set = Number(p && p.discountPercent);
  if (Number.isFinite(set) && set > 0) return Math.min(MAX_PCT, Math.round(set));
  const old = Number(p && p.oldPrice), price = Number(p && p.price);
  if (Number.isFinite(old) && Number.isFinite(price) && price > 0 && old > price) {
    return Math.min(MAX_PCT, Math.round((1 - price / old) * 100));
  }
  return 0;
}

// Цена, по которой товар продаётся. Отдельной цены по акции больше нет, но
// спрашивать «сколько стоит» весь проект продолжает здесь — здесь же и
// нормализация числа.
function effectivePrice(p) { return Number(p && p.price) || 0; }

/* Зачёркнутая цена для ЛЮБОЙ суммы сборки: база, база с памятью, база с памятью
 * и ремешком — процент от этого не зависит.
 *
 * Округление до десятки: без него старая цена выходит с копейками
 * (67 990 / 0.94 = 72 329,78), а с ним процент, посчитанный покупателем обратно
 * от показанных чисел, сходится с заявленным — расхождение меньше сотой
 * процента. Ноль означает «зачёркивать нечего».
 */
function compareFor(sum, pct) {
  const total = Number(sum), percent = Number(pct);
  if (!(total > 0) || !(percent > 0) || percent > MAX_PCT) return 0;
  return Math.round(total / (1 - percent / 100) / 10) * 10;
}

// Зачёркнутая цена базовой сборки — то, что показывает карточка каталога.
function comparePrice(p) { return compareFor(effectivePrice(p), discountPct(p)); }

/* Перевод товара со старой модели на процент — так, чтобы витрина показывала
 * ТУ ЖЕ пару чисел, что и вчера. Правила прежней модели повторены здесь по
 * шагам, потому что больше их взять негде:
 *
 *   - активная «горящая скидка» (`hotDeal` + цена ниже базовой + срок не вышел)
 *     была настоящей ценой продажи, а зачёркивалась базовая цена товара;
 *   - без акции продавали по `price`, а зачёркивали `oldPrice`, если он выше.
 *
 * Отсюда `price` нового товара — то, за что он реально продавался, а процент —
 * тот, что видел покупатель. Иначе снятие акции молча подняло бы цену: у пяти
 * товаров каталога она держалась именно на ней.
 *
 * Пользуются этим переносом два места: разовый скрипт `scripts/migrate-discount.js`
 * и переезд с мультидоменной версии в lib/db.js.
 */
function fromLegacy(product, now) {
  const p = product || {};
  const base = Number(p.price) || 0;
  const deal = Number(p.hotDealPrice) || 0;
  const until = Number(p.hotDealUntil) || 0;
  const active = !!p.hotDeal && deal > 0 && deal < base && (!until || until > (now || Date.now()));
  // Активная акция: продавали по её цене, зачёркивали базовую.
  if (active) {
    return { price: deal, percent: Math.min(MAX_PCT, Math.round((1 - deal / base) * 100)) };
  }
  // Всё остальное — обычный товар, и процент у него берётся там же, где его
  // берёт витрина: своё поле, а если его ещё нет — прежняя пара цен. Именно
  // поэтому перенос идемпотентен: у уже переведённого товара он ничего не
  // меняет, а не обнуляет скидку, «не найдя» старой цены.
  return { price: base, percent: discountPct(p) };
}

module.exports = { MAX_PCT, discountPct, effectivePrice, compareFor, comparePrice, fromLegacy };
