'use strict';
/* ==================== Поиск по каталогу: по словам и по-русски ====================
 *
 * Раньше поиск был одной строкой: `name+category+shortDesc+specs`.toLowerCase()
 * .includes(запрос). Подстрока целиком — и этого хватало ровно до первого живого
 * запроса. Замеры на текущем каталоге:
 *
 *   «macbook air m5» → 0 карточек (товар есть: `MacBook Air 13" (M5)`, но между
 *                      словами стоит `13"` и подстрокой запрос не ложится);
 *   «айфон»          → 0;   «айфон 17» → 0;   «макбук» → 0;
 *   «аирподс»        → 0;   «часы»     → 0;   «про макс» → 0.
 *
 * То есть покупатель русского магазина, набравший «айфон 17», видел «Ничего не
 * найдено» при четырнадцати айфонах в каталоге. Это не придирка к формулировке:
 * поиск в шапке стоит на каждой странице, и пустая выдача по своему же товару —
 * прямая потеря покупки.
 *
 * Лечится двумя правилами:
 *
 *   1. ЗАПРОС БЬЁТСЯ НА СЛОВА, и каждое слово обязано найтись (И, а не ИЛИ).
 *      «macbook air m5» — это три условия к одному товару, а не одна строка.
 *      ИЛИ здесь не годится: «iphone 17» отдавал бы заодно `iPad mini (A17 Pro)`
 *      ради одной семнадцатки.
 *
 *   2. К товару приписываются РУССКИЕ СЛОВА, которыми его называют вслух
 *      (`WORDS`). Каталог набран латиницей, а ищут в нём кириллицей — и проект
 *      это уже знает: в `lib/demo-reviews.js` лежит `CASUAL_NAMES` ровно с теми
 *      же «айфон», «макбук», «ультра», «эйртег». Тут та же таблица, но с другой
 *      стороны прилавка.
 *
 * Порядок выдачи НЕ трогаем: он задан в панели перетаскиванием (см. «Порядок
 * товаров на главной» в CLAUDE.md), и подменять его релевантностью — значит
 * молча отменять расстановку, сделанную руками.
 *
 * Отбор строится один раз на товар и кэшируется по ССЫЛКЕ на объект — тот же
 * приём, что у `reviewIndex()` в `lib/db.js`: `readJson` отдаёт один и тот же
 * объект, пока не изменился mtime файла, поэтому WeakMap сам протухает вместе с
 * перечитанным каталогом, и своей проверки свежести не нужно.
 */

/* Слова, которыми технику называют по-русски. Ключ — регулярка по «название +
 * категория» товара, значение — что дописать в строку поиска.
 *
 * Формы выписаны РУКАМИ и по нескольку на слово («наушники наушник наушников»),
 * а не сведены к основе. Соблазн оставить одну основу велик, но направление
 * сравнения здесь обратное: ищем `haystack.includes(слово запроса)`, поэтому
 * основа «наушник» запрос «наушники» как раз НЕ ловит. Проверять надо тем, что
 * набирает покупатель, а набирает он именительный падеж и множественное число.
 *
 * Сюда же уходит латиница, которую набирают кириллицей вслепую («вотч»,
 * «эйр»): раскладку покупатель переключать не обязан.
 */
const WORDS = [
  [/iphone/, 'айфон айфоны афон телефон телефоны смартфон смартфоны мобильник'],
  [/ipad/, 'айпад айпады планшет планшеты'],
  [/macbook/, 'макбук макбуки ноутбук ноутбуки лаптоп мак'],
  [/imac/, 'аймак мак компьютер моноблок'],
  [/mac mini/, 'мак мини компьютер'],
  [/mac studio/, 'мак студио компьютер'],
  [/studio display/, 'студио дисплей монитор экран'],
  [/apple watch/, 'эпл вотч часы смарт-часы смартчасы'],
  [/airpods max/, 'аирподс макс наушники наушник накладные полноразмерные'],
  [/airpods/, 'аирподс эирподс эйрподс наушники наушник затычки'],
  [/apple tv/, 'эпл тиви приставка телеприставка'],
  [/homepod/, 'хоумпод колонка колонки'],
  [/vision/, 'вижн очки шлем гарнитура'],
  [/airtag/, 'эйртег эиртаг метка метки трекер брелок поисковый'],
  // Приставки моделей — их тоже набирают кириллицей: «17 про макс», «эйр».
  [/\bpro max\b/, 'про макс промакс'],
  [/\bpro\b/, 'про'],
  [/\bmax\b/, 'макс'],
  [/\bair\b/, 'эйр аир'],
  [/\bmini\b/, 'мини'],
  [/\bplus\b/, 'плюс'],
  [/\bultra\b/, 'ультра'],
  [/\bseries\b/, 'серия'],
  [/\bse\b/, 'се'],
  // Бренд ищут и так, и так — а в названиях товаров слова «apple» чаще нет вовсе.
  [/./, 'apple эпл эппл']
];

// Приведение к виду, в котором сравниваем: строчные, `ё` неотличима от `е`,
// любой не-буквенно-цифровой знак — пробел. Кавычки в `13"`, скобки в `(M5)` и
// дефис в «смарт-часы» иначе прилипали бы к слову и ломали совпадение.
function normalize(value) {
  return String(value == null ? '' : value)
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/[^a-zа-я0-9]+/gi, ' ')
    .trim();
}

/* Русские слова для товара: все правила, чьи регулярки совпали.
 *
 * Сверяемся с НАЗВАНИЕМ, а не с «название + категория». Категория здесь только
 * вредит: `HomePod` лежит в разделе «Apple TV и Дом», и правило `/apple tv/`
 * выдавало колонке слова «приставка, телеприставка» — запрос «приставка»
 * отдавал три карточки вместо одной. Названия при этом самодостаточны: слово,
 * по которому мы узнаём линейку, стоит в имени каждого товара каталога.
 *
 * Сама категория в поиске остаётся — она попадает в строку как обычный текст.
 */
function wordsFor(name) {
  const key = String(name || '').toLowerCase();
  let out = '';
  for (const [re, words] of WORDS) if (re.test(key)) out += ' ' + words;
  return out;
}

const cache = new WeakMap();

/* Строка, по которой ищем. Кроме полей товара в неё входят русские слова и
 * СКЛЕЙКА НАЗВАНИЯ без пробелов: «iphone17» и «airpodspro» набирают слитно
 * ничуть не реже, чем через пробел, а подстрокой они иначе не находятся.
 *
 * Склеивается именно название, а не весь текст: у склейки характеристик слова
 * срастались бы через границу строк («…Max» + «48 Мп» → «max48»), и запрос
 * ловил бы товар за то, чего в нём никто не писал.
 */
function haystack(product) {
  if (!product || typeof product !== 'object') return '';
  const hit = cache.get(product);
  if (hit !== undefined) return hit;
  const base = normalize([product.name, product.category, product.shortDesc, product.specs]
    .filter(Boolean).join(' '));
  const glued = normalize(product.name).replace(/ /g, '');
  const text = base + ' ' + glued + ' ' + normalize(wordsFor(product.name));
  cache.set(product, text);
  return text;
}

// Слова запроса. Пустой запрос — пустой список, и тогда отбора нет вовсе.
function terms(query) {
  const q = normalize(query);
  return q ? q.split(' ').slice(0, 12) : [];
}

// Товар подходит, когда нашлось КАЖДОЕ слово запроса.
function matches(product, query) {
  const list = terms(query);
  if (!list.length) return true;
  const text = haystack(product);
  return list.every(t => text.includes(t));
}

// Отбор с сохранением порядка каталога.
function filter(products, query) {
  const list = terms(query);
  if (!list.length) return (products || []).slice();
  return (products || []).filter(p => {
    const text = haystack(p);
    return list.every(t => text.includes(t));
  });
}

module.exports = { normalize, terms, haystack, matches, filter, WORDS };
