  RELEASE_DATES,
  REGIONAL_NAMES: REGIONAL_MALE.concat(REGIONAL_FEMALE),
  NICKNAMES: NICK_NEUTRAL.concat(NICK_MALE, NICK_FEMALE),
  LATIN_NAMES,
