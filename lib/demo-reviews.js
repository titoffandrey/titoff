// Границу слова задаём вручную: \b в JS не знает кириллицы.
const ALIGN_RULES = GENDER_FORMS.flatMap(([male, female]) => [[male, female], [capitalize(male), capitalize(female)]])
  .map(([male, female]) => ({
    male, female,
    maleRe: new RegExp(`(^|[^А-Яа-яЁё])${male}(?=$|[^А-Яа-яЁё])`, 'gu'),
    femaleRe: new RegExp(`(^|[^А-Яа-яЁё])${female}(?=$|[^А-Яа-яЁё])`, 'gu')
  }));

function alignPhrase(phrase, persona) {
  const female = persona.gender === 'female';
  let out = phrase;
  for (const rule of ALIGN_RULES) {
    const wanted = female ? rule.female : rule.male;
    const pattern = female ? rule.maleRe : rule.femaleRe;
    pattern.lastIndex = 0;
    out = out.replace(pattern, (_, prefix) => prefix + wanted);
  }
  return out;
}

