/*
 * Упоминание чужой площадки в тексте отзыва.
 *
 * Отзыв, где написано «заказывала на озоне» или «пришло с вайлдберриз», на
 * витрине НАШЕГО магазина читается как рассказ о покупке в другом месте. Это то
 * же правило, что у демо-набора («конкретные сети и маркетплейсы не называем»),
 * и привезённые с площадки отзывы не исключение.
 *
 * Правило одно на весь проект: по нему отсеивает `scripts/import-ozon-reviews.js`
 * при заливке и `scripts/drop-marketplace-reviews.js` — то, что успело приехать
 * до его появления. Две копии разъехались бы молча, а увидеть это можно было бы
 * только глазами на витрине.
 *
 * `\bdns\b` пишется латиницей: кириллическая «ДНС» ловится соседним `днс`, а
 * латинского написания правило не ловило вовсе — в строке стояло «дns», то есть
 * кириллическая «д» с латинскими буквами, и такое не встречается нигде.
 */
const MARKETPLACE_RE =
  /озон|ozon|вайлдберриз|wildberries|\bwb\b|яндекс\s*маркет|алиэкспресс|aliexpress|\bdns\b|днс|мвидео|м\.видео|эльдорадо|ситилинк/i;

function mentionsMarketplace(text) {
  return MARKETPLACE_RE.test(String(text || ''));
}

module.exports = { MARKETPLACE_RE, mentionsMarketplace };
