#!/bin/sh
# Ежедневное обновление дат демо-отзывов.
#
# Зачем: reviewDate() растягивает даты от релиза товара до «сегодня», поэтому
# набор, сгенерированный один раз, через месяц показывает самый свежий отзыв
# месячной давности — витрина выглядит заброшенной.
#
# Почему это дёшево: от текущей даты зависят только createdAt. Тексты, авторы и
# оценки берутся из ГПСЧ с сидом «id товара:номер» и от времени не зависят,
# поэтому повторный прогон не переписывает ленту заново, а сдвигает её вперёд.
#
# Отзывы покупателей и добавленные владельцем фото сохраняет сам
# scripts/demo-reviews.js — он опознаёт демо-записи по служебным полям.
#
# Пути можно переопределить переменными окружения: на боевом сервере проект
# лежит в /home/titoff/istore, а данные — в /var/lib/apple-store.
set -eu

PROJECT="${PROJECT_DIR:-$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)}"
STORE_DATA_DIR="${STORE_DATA_DIR:-$PROJECT/data}"
export STORE_DATA_DIR
NODE_BIN="${NODE_BIN:-node}"
BACKUP_DIR="$STORE_DATA_DIR/backups"

# Одна откатная копия перед перезаписью: файл переписывается каждый день, и
# потерять вместе с демо-набором реальные отзывы нельзя.
if [ -f "$STORE_DATA_DIR/reviews.json" ]; then
  mkdir -p "$BACKUP_DIR"
  cp -p "$STORE_DATA_DIR/reviews.json" "$BACKUP_DIR/reviews-before-refresh.json"
fi

cd "$PROJECT"
# Новый товар без записей в REVIEW_COUNTS/RELEASE_DATES обрушит скрипт, и это
# защита: исключение бросается до записи, данные остаются целыми.
"$NODE_BIN" scripts/demo-reviews.js --apply
