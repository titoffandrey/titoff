#!/bin/bash
# Выкатка текущего дерева на ВСЕ сайты из deploy/sites.txt — запускается С НОУТБУКА.
#
#   ./deploy/deploy-all.sh              # все сайты из списка
#   ./deploy/deploy-all.sh adcappl.com  # только названные домены (по одному аргументу на домен)
#
# Код у сайтов один, и правка обязана доехать до каждого: выкатка на один сайт
# из двух оставляет второй на старом коде молча — по витрине это не видно,
# пока не откроешь нужную страницу. Поэтому по умолчанию выкатываются все, а
# один сайт называют явно и осознанно.
#
# Каждый сайт выкатывается своим `deploy/install.sh <алиас> <домен>` со всеми
# его проверками (Tor-алиас, отметка выкаченного коммита, `PUBLIC_ORIGIN`).
# Отказ на одном сайте не останавливает остальные: причина у него своя (Tor
# не поднялся, сервер перезагружался), и второй сайт от этого не должен
# отставать. Итог печатается по каждому сайту в конце, код возврата — ненулевой,
# если хоть один не выкатился.
set -uo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
LIST="$ROOT/deploy/sites.txt"
[ -f "$LIST" ] || { echo "Нет списка сайтов: $LIST"; exit 1; }

# Выкатывать — только из закоммиченного дерева: незакоммиченное восстановить
# неоткуда, а на двух серверах ещё и разъедется. install.sh об этом
# предупреждает; здесь, где серверов несколько, это остановка.
if [ -n "$(git -C "$ROOT" status --porcelain 2>/dev/null)" ] && [ "${FORCE_DEPLOY:-}" != '1' ]; then
  echo 'СТОП. В рабочем дереве есть незакоммиченные правки — сначала закоммитьте их.'
  git -C "$ROOT" status --short | head -20
  echo 'Осознанно выкатить как есть — FORCE_DEPLOY=1.'
  exit 1
fi

declare -a RESULTS=()
FAILED=0
FOUND=0
while read -r ALIAS DOMAIN _; do
  case "$ALIAS" in ''|'#'*) continue;; esac
  if [ "$#" -gt 0 ]; then
    WANT=0
    for arg in "$@"; do [ "$arg" = "$DOMAIN" ] && WANT=1; done
    [ "$WANT" = 1 ] || continue
  fi
  FOUND=$((FOUND + 1))
  echo
  echo "################ $DOMAIN ($ALIAS) ################"
  "$ROOT/deploy/install.sh" "$ALIAS" "$DOMAIN"
  CODE=$?
  if [ "$CODE" = 0 ]; then
    RESULTS+=("  ✓ $DOMAIN")
  elif [ "$CODE" = 2 ]; then
    # install.sh выходит двойкой ровно в одном случае: код на сервере уже
    # новый, а отметку выкатки записать не удалось (см. его хвост).
    RESULTS+=("  ⚠ $DOMAIN — выкачен, но отметка deployed-from.txt не записана (см. выше, запишите руками)")
    FAILED=$((FAILED + 1))
  else
    RESULTS+=("  ✗ $DOMAIN — НЕ ВЫКАЧЕН")
    FAILED=$((FAILED + 1))
  fi
done < "$LIST"

if [ "$FOUND" = 0 ]; then
  echo 'Ни одного сайта не выбрано: проверьте deploy/sites.txt и аргументы.'
  exit 1
fi

echo
echo '================ Итог выкатки ================'
printf '%s\n' "${RESULTS[@]}"
[ "$FAILED" = 0 ] || { echo "Не выкатилось сайтов: $FAILED"; exit 1; }
